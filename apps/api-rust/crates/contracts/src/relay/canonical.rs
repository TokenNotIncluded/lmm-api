//! Provider-neutral relay model.
//!
//! This is intentionally smaller than any provider DTO: unsupported fields
//! are rejected or recorded by [`LossReport`] instead of being smuggled
//! through as an untyped JSON envelope.

use serde::{Deserialize, Serialize};

use super::JsonData;

/// Google-documented placeholder for a synthetic non-Gemini tool history.
pub const GEMINI_SYNTHETIC_THOUGHT_SIGNATURE: &str = "context_engineering_is_the_way_to_go";

#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Protocol {
    OpenAi,
    OpenAiResponses,
    Claude,
    Gemini,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum FixtureKind {
    Request,
    Response,
    Stream,
}

#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Role {
    System,
    Developer,
    User,
    Assistant,
    Tool,
    Model,
}

