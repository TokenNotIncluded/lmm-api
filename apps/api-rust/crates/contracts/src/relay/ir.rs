/// An ordered provider-neutral envelope.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Envelope {
    /// Protocol which supplied this envelope.
    pub source: Protocol,
    /// Model identifier retained exactly as supplied by the caller.
    pub model: String,
    /// Ordered semantic items.  Position is part of the protocol meaning.
    #[serde(default)]
    items: Vec<Item>,
    /// Ordered tool declarations.
    #[serde(default)]
    pub tools: Vec<Tool>,
    /// Tool selection policy.
    #[serde(default)]
    pub tool_choice: ToolChoice,
    /// Stable generation controls.
    #[serde(default)]
    pub controls: GenerationControls,
    /// Stateful continuation references.
    #[serde(default)]
    pub state: StateRefs,
    /// Semantic usage and cache/billing counters.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub usage: Option<SemanticUsage>,
    /// Losses accumulated by explicit IR mutations.
    #[serde(default)]
    losses: LossLedger,
    /// Unknown envelope fields retained for round trips.
    #[serde(flatten)]
    #[serde(default)]
    pub extensions: ExtensionBag,
}

impl Envelope {
    /// Creates an empty envelope with deterministic default controls and state.
    #[must_use]
    pub fn new(source: Protocol, model: impl Into<String>) -> Self {
        Self {
            source,
            model: model.into(),
            items: Vec::new(),
            tools: Vec::new(),
            tool_choice: ToolChoice::default(),
            controls: GenerationControls::default(),
            state: StateRefs::default(),
            usage: None,
            losses: LossLedger::new(),
            extensions: ExtensionBag::new(),
        }
    }

    /// Returns the ordered item slice without copying or reindexing it.
    #[must_use]
    pub fn ordered_items(&self) -> &[Item] {
        &self.items
    }

    /// Records a structured loss exactly once in the envelope ledger.
    pub fn record_loss(&mut self, loss: Loss) {
        self.losses.record(loss);
    }

    /// Returns the automatically accumulated loss ledger.
    #[must_use]
    pub fn loss_ledger(&self) -> &LossLedger {
        &self.losses
    }

    /// Adds an item while rejecting an orphan tool result or invalid opaque state.
    pub fn push_item(&mut self, item: Item) -> Result<(), IrValidationError> {
        self.items.push(item);
        if let Err(error) = self.validate() {
            let new_len = self.items.len().saturating_sub(1);
            self.items.truncate(new_len);
            return Err(error);
        }
        Ok(())
    }

    /// Adds a Part to an existing item while retaining its position.
    pub fn push_part(&mut self, item_index: usize, part: Part) -> Result<(), IrMutationError> {
        if item_index >= self.items.len() {
            return Err(IrMutationError::IndexOutOfBounds {
                collection: OrderedCollection::Parts,
                index: item_index,
                len: self.items.len(),
            });
        }
        self.items[item_index].parts.push(part);
        if let Err(error) = self.validate() {
            let _ = self.items[item_index].parts.pop();
            return Err(error.into());
        }
        Ok(())
    }

    /// Removes one item only when the caller supplies the corresponding loss.
    pub fn remove_item(
        &mut self,
        index: usize,
        loss: Option<Loss>,
    ) -> Result<Item, IrMutationError> {
        let loss = require_loss(loss, MutationKind::RemoveItem)?;
        if index >= self.items.len() {
            return Err(IrMutationError::IndexOutOfBounds {
                collection: OrderedCollection::Items,
                index,
                len: self.items.len(),
            });
        }
        let removed = self.items.remove(index);
        if let Err(error) = self.validate() {
            self.items.insert(index, removed);
            return Err(error.into());
        }
        self.losses.record(loss);
        Ok(removed)
    }

    /// Removes one Part only when the caller supplies the corresponding loss.
    pub fn remove_part(
        &mut self,
        item_index: usize,
        part_index: usize,
        loss: Option<Loss>,
    ) -> Result<Part, IrMutationError> {
        let loss = require_loss(loss, MutationKind::RemovePart)?;
        if item_index >= self.items.len() {
            return Err(IrMutationError::IndexOutOfBounds {
                collection: OrderedCollection::Items,
                index: item_index,
                len: self.items.len(),
            });
        }
        let item_part_len = self.items[item_index].parts.len();
        if part_index >= item_part_len {
            return Err(IrMutationError::IndexOutOfBounds {
                collection: OrderedCollection::Parts,
                index: part_index,
                len: item_part_len,
            });
        }
        let removed = self.items[item_index].parts.remove(part_index);
        if let Err(error) = self.validate() {
            self.items[item_index].parts.insert(part_index, removed);
            return Err(error.into());
        }
        self.losses.record(loss);
        Ok(removed)
    }

    /// Reorders two items only with an explicit content-order loss.
    pub fn reorder_items(
        &mut self,
        from: usize,
        to: usize,
        loss: Option<Loss>,
    ) -> Result<(), IrMutationError> {
        let loss = require_loss(loss, MutationKind::ReorderItems)?;
        check_index(from, OrderedCollection::Items, self.items.len())?;
        check_index(to, OrderedCollection::Items, self.items.len())?;
        let items_before = self.items.clone();
        if from != to {
            let item = self.items.remove(from);
            self.items.insert(to, item);
        }
        if let Err(error) = self.validate() {
            self.items = items_before;
            return Err(error.into());
        }
        self.losses.record(loss);
        Ok(())
    }

    /// Reorders two Parts only with an explicit content-order loss.
    pub fn reorder_parts(
        &mut self,
        item_index: usize,
        from: usize,
        to: usize,
        loss: Option<Loss>,
    ) -> Result<(), IrMutationError> {
        let loss = require_loss(loss, MutationKind::ReorderParts)?;
        if item_index >= self.items.len() {
            return Err(IrMutationError::IndexOutOfBounds {
                collection: OrderedCollection::Items,
                index: item_index,
                len: self.items.len(),
            });
        }
        let part_len = self.items[item_index].parts.len();
        check_index(from, OrderedCollection::Parts, part_len)?;
        check_index(to, OrderedCollection::Parts, part_len)?;
        let item_before = self.items[item_index].clone();
        if from != to {
            let part = self.items[item_index].parts.remove(from);
            self.items[item_index].parts.insert(to, part);
        }
        if let Err(error) = self.validate() {
            self.items[item_index] = item_before;
            return Err(error.into());
        }
        self.losses.record(loss);
        Ok(())
    }

    /// Merges adjacent items only when a structured merge loss is supplied.
    ///
    /// Items must have the same kind, role, provenance, and no competing
    /// identity/raw fields.  Rejecting incompatible values prevents the merge
    /// API from silently discarding fields even after a loss is recorded.
    pub fn merge_items(
        &mut self,
        left: usize,
        right: usize,
        loss: Option<Loss>,
    ) -> Result<(), IrMutationError> {
        let loss = require_loss(loss, MutationKind::MergeItems)?;
        check_adjacent(left, right, OrderedCollection::Items, self.items.len())?;
        let left_before = self.items[left].clone();
        let right_before = self.items[right].clone();
        validate_item_merge(&left_before, &right_before)?;
        let right_item = self.items.remove(right);
        self.items[left].parts.extend(right_item.parts);
        self.items[left].extensions.extend(right_item.extensions);
        if let Err(error) = self.validate() {
            let _merged = self.items.remove(left);
            self.items.insert(left, left_before);
            self.items.insert(right, right_before);
            return Err(error.into());
        }
        self.losses.record(loss);
        Ok(())
    }

    /// Merges adjacent compatible Parts only with an explicit merge loss.
    pub fn merge_parts(
        &mut self,
        item_index: usize,
        left: usize,
        right: usize,
        loss: Option<Loss>,
    ) -> Result<(), IrMutationError> {
        let loss = require_loss(loss, MutationKind::MergeParts)?;
        if item_index >= self.items.len() {
            return Err(IrMutationError::IndexOutOfBounds {
                collection: OrderedCollection::Items,
                index: item_index,
                len: self.items.len(),
            });
        }
        let part_len = self.items[item_index].parts.len();
        check_adjacent(left, right, OrderedCollection::Parts, part_len)?;
        let merged = merge_part_values(
            &self.items[item_index].parts[left],
            &self.items[item_index].parts[right],
        )?;
        let item_before = self.items[item_index].clone();
        self.items[item_index].parts[left] = merged;
        self.items[item_index].parts.remove(right);
        if let Err(error) = self.validate() {
            self.items[item_index] = item_before;
            return Err(error.into());
        }
        self.losses.record(loss);
        Ok(())
    }

    /// Validates tool-result references and opaque-state invariants.
    pub fn validate(&self) -> Result<(), IrValidationError> {
        let mut calls = BTreeMap::<String, usize>::new();
        let mut results = BTreeMap::<String, usize>::new();
        for (field, identifier) in [
            ("conversation_id", self.state.conversation_id.as_ref()),
            (
                "previous_response_id",
                self.state.previous_response_id.as_ref(),
            ),
        ] {
            if identifier.is_some_and(|value| value.is_empty()) {
                return Err(IrValidationError::EmptyStateId {
                    field: field.to_owned(),
                });
            }
        }
        for (index, item) in self.items.iter().enumerate() {
            validate_item(item, index)?;
            if let Some(id) = item.id.as_ref() {
                if id.is_empty() {
                    return Err(IrValidationError::EmptyOpaqueId {
                        item_index: index,
                        field: "id".to_owned(),
                    });
                }
            }
            if let Some(call_id) = item.call_id.as_ref() {
                if call_id.is_empty() {
                    return Err(IrValidationError::EmptyOpaqueId {
                        item_index: index,
                        field: "call_id".to_owned(),
                    });
                }
            }
            match &item.kind {
                ItemKind::ToolCall => {
                    let Some(call_id) = item.call_id.as_ref() else {
                        return Err(IrValidationError::MissingToolCallId { item_index: index });
                    };
                    let call_key = call_id.as_str().to_owned();
                    if let Some(first_item_index) = calls.insert(call_key, index) {
                        return Err(IrValidationError::DuplicateToolCallId {
                            first_item_index,
                            second_item_index: index,
                            call_id: call_id.clone(),
                        });
                    }
                }
                ItemKind::ToolResult => {
                    let Some(call_id) = item.call_id.as_ref() else {
                        return Err(IrValidationError::MissingToolCallId { item_index: index });
                    };
                    let call_key = call_id.as_str();
                    if !calls.contains_key(call_key) {
                        return Err(IrValidationError::OrphanToolResult {
                            item_index: index,
                            call_id: call_id.clone(),
                        });
                    }
                    if let Some(first_item_index) = results.insert(call_key.to_owned(), index) {
                        return Err(IrValidationError::DuplicateToolResult {
                            first_item_index,
                            second_item_index: index,
                            call_id: call_id.clone(),
                        });
                    }
                }
                _ => {}
            }
        }
        Ok(())
    }

    /// Checks whether this envelope belongs to the exact, lossless subset.
    pub fn validate_exact_round_trip(&self) -> Result<(), ExactRoundTripError> {
        if !self.losses.is_empty() {
            return Err(ExactRoundTripError::LossesPresent {
                losses: self.losses.clone(),
            });
        }
        self.validate().map_err(ExactRoundTripError::Validation)?;
        if let Some(error) = exact_synthetic_id_error(self) {
            return Err(error);
        }
        for (item_index, item) in self.items.iter().enumerate() {
            if matches!(&item.kind, ItemKind::Unknown(_)) {
                return Err(ExactRoundTripError::UnmodeledField {
                    path: format!("items[{item_index}].kind"),
                });
            }
            if item.raw.is_some() {
                return Err(ExactRoundTripError::UnmodeledField {
                    path: format!("items[{item_index}].raw"),
                });
            }
            if !item.extensions.is_empty() || !item.provenance.extensions.is_empty() {
                return Err(ExactRoundTripError::UnmodeledField {
                    path: format!("items[{item_index}].extensions"),
                });
            }
            for (part_index, part) in item.parts.iter().enumerate() {
                if matches!(&part.kind, PartKind::Unknown(_)) || !part.extensions.is_empty() {
                    return Err(ExactRoundTripError::UnmodeledField {
                        path: format!("items[{item_index}].parts[{part_index}]"),
                    });
                }
                if part
                    .opaque
                    .as_ref()
                    .is_some_and(|state| state.provenance == OpaqueStateProvenance::Synthetic)
                {
                    return Err(ExactRoundTripError::SyntheticOpaqueState {
                        item_index,
                        part_index,
                    });
                }
                if let Some(media) = part.media.as_ref() {
                    if matches!(&media.kind, MediaKind::Unknown(_))
                        || media.data.is_some()
                        || !media.extensions.is_empty()
                    {
                        return Err(ExactRoundTripError::UnmodeledField {
                            path: format!("items[{item_index}].parts[{part_index}].media"),
                        });
                    }
                }
                if let Some(function) = part.function.as_ref() {
                    if matches!(&function.kind, FunctionKind::Unknown(_))
                        || !function.extensions.is_empty()
                    {
                        return Err(ExactRoundTripError::UnmodeledField {
                            path: format!("items[{item_index}].parts[{part_index}].function"),
                        });
                    }
                }
            }
        }
        if !self.extensions.is_empty()
            || !self.controls.extensions.is_empty()
            || !self.state.extensions.is_empty()
            || self.tools.iter().any(|tool| {
                matches!(&tool.kind, ToolKind::Unknown(_)) || !tool.extensions.is_empty()
            })
        {
            return Err(ExactRoundTripError::UnmodeledField {
                path: "envelope.extensions".to_owned(),
            });
        }
        if matches!(&self.tool_choice, ToolChoice::Provider { .. }) {
            return Err(ExactRoundTripError::UnmodeledField {
                path: "tool_choice.provider".to_owned(),
            });
        }
        if let Some(usage) = self.usage.as_ref() {
            if !usage.extensions.is_empty()
                || !usage.cache.extensions.is_empty()
                || usage
                    .billing
                    .as_ref()
                    .is_some_and(|billing| !billing.extensions.is_empty())
            {
                return Err(ExactRoundTripError::UnmodeledField {
                    path: "usage.extensions".to_owned(),
                });
            }
        }
        Ok(())
    }

    /// Returns whether exact round-trip invariants currently hold.
    #[must_use]
    pub fn is_exact_round_trip_safe(&self) -> bool {
        self.validate_exact_round_trip().is_ok()
    }
}

/// A mutation operation which requires an accompanying loss entry.
#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum MutationKind {
    /// Remove an ordered item.
    RemoveItem,
    /// Remove an ordered Part.
    RemovePart,
    /// Merge adjacent ordered items.
    MergeItems,
    /// Merge adjacent ordered Parts.
    MergeParts,
    /// Reorder ordered items.
    ReorderItems,
    /// Reorder ordered Parts.
    ReorderParts,
}

/// Which ordered collection produced an index error or merge error.
#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum OrderedCollection {
    /// The envelope item vector.
    Items,
    /// An item Part vector.
    Parts,
}

/// Errors returned by explicit ordered mutations.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
pub enum IrMutationError {
    /// The caller attempted a lossy mutation without a structured Loss.
    MissingLoss {
        /// Mutation which was refused.
        operation: MutationKind,
    },
    /// An item or Part index is outside its ordered vector.
    IndexOutOfBounds {
        /// Collection being addressed.
        collection: OrderedCollection,
        /// Requested index.
        index: usize,
        /// Current collection length.
        len: usize,
    },
    /// A merge requires adjacent values so their order is unambiguous.
    NonAdjacent {
        /// Collection being merged.
        collection: OrderedCollection,
        /// Left index supplied by the caller.
        left: usize,
        /// Right index supplied by the caller.
        right: usize,
    },
    /// The values have fields whose semantic ownership cannot be merged safely.
    MergeConflict {
        /// Collection being merged.
        collection: OrderedCollection,
        /// Safe reason code, without source content.
        reason: String,
    },
    /// The proposed mutation would violate a tool-link or opaque-state invariant.
    Validation(IrValidationError),
}

/// Validation failures for ordered tool links and provider state.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
pub enum IrValidationError {
    /// A tool call or result does not have an opaque call identifier.
    MissingToolCallId {
        /// Item whose identifier is missing.
        item_index: usize,
    },
    /// A tool result points to no ordered tool call.
    OrphanToolResult {
        /// Orphan result item.
        item_index: usize,
        /// Unmatched call identifier.
        call_id: OpaqueId,
    },
    /// A tool result reuses a call identifier which already has a result.
    DuplicateToolResult {
        /// First result item using the identifier.
        first_item_index: usize,
        /// Later result item reusing the identifier.
        second_item_index: usize,
        /// Duplicated identifier.
        call_id: OpaqueId,
    },
    /// Two tool calls reused one opaque identifier.
    DuplicateToolCallId {
        /// First item using the identifier.
        first_item_index: usize,
        /// Later item reusing the identifier.
        second_item_index: usize,
        /// Duplicated identifier.
        call_id: OpaqueId,
    },
    /// An item or tool link contains an empty opaque identifier.
    EmptyOpaqueId {
        /// Item containing the empty identifier.
        item_index: usize,
        /// Identifier field which was empty.
        field: String,
    },
    /// An envelope state reference contains an empty opaque identifier.
    EmptyStateId {
        /// State field which was empty.
        field: String,
    },
    /// A Part carries a payload which does not match its declared kind.
    InvalidPartShape {
        /// Item containing the malformed Part.
        item_index: usize,
        /// Malformed Part index.
        part_index: usize,
        /// Stable reason code, without source content.
        reason: String,
    },
    /// A function Part has incompatible or incomplete operation fields.
    InvalidFunctionShape {
        /// Item containing the malformed Part.
        item_index: usize,
        /// Malformed Part index.
        part_index: usize,
        /// Stable reason code, without source content.
        reason: String,
    },
    /// An ordered item has an invalid relationship to its function Parts.
    InvalidItemShape {
        /// Item containing the malformed function relationship.
        item_index: usize,
        /// Stable reason code, without source content.
        reason: String,
    },
    /// An opaque state provider or kind is empty.
    InvalidOpaqueState {
        /// Item containing the invalid state.
        item_index: usize,
        /// Part containing the invalid state.
        part_index: usize,
        /// Field which failed validation.
        field: String,
    },
}

/// Failures returned by the exact round-trip invariant helper.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
pub enum ExactRoundTripError {
    /// The envelope already contains a structured loss.
    LossesPresent {
        /// Losses preventing an exact claim.
        losses: LossLedger,
    },
    /// The ordered envelope has an invalid tool or opaque-state relation.
    Validation(IrValidationError),
    /// Synthetic provider state is not exact source state.
    SyntheticOpaqueState {
        /// Item containing the synthetic state.
        item_index: usize,
        /// Part containing the synthetic state.
        part_index: usize,
    },
    /// A synthetic identifier cannot claim exact source provenance.
    SyntheticOpaqueId {
        /// Item containing the identifier, when the identifier belongs to an
        /// item rather than envelope state.
        item_index: Option<usize>,
        /// Stable field path, without identifier contents.
        field: String,
    },
    /// A raw, unknown, or extension field is outside the typed exact subset.
    UnmodeledField {
        /// Structural field path, without source payload contents.
        path: String,
    },
}

/// A malformed opaque provider state independent of any item location.
#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum OpaqueStateError {
    /// Provider name is empty.
    EmptyProvider,
    /// Provider state kind is empty.
    EmptyKind,
}

/// Checks the invariant that authentic and synthetic provider state remains
/// explicitly distinguished and has a stable provider/kind identity.
pub fn validate_opaque_state_invariant(
    state: &OpaqueProviderState,
) -> Result<(), OpaqueStateError> {
    if state.provider.trim().is_empty() {
        return Err(OpaqueStateError::EmptyProvider);
    }
    if state.kind.trim().is_empty() {
        return Err(OpaqueStateError::EmptyKind);
    }
    Ok(())
}

fn exact_synthetic_id_error(envelope: &Envelope) -> Option<ExactRoundTripError> {
    let state_ids = [
        (
            "state.conversation_id",
            envelope.state.conversation_id.as_ref(),
        ),
        (
            "state.previous_response_id",
            envelope.state.previous_response_id.as_ref(),
        ),
    ];
    for (field, identifier) in state_ids {
        if identifier.is_some_and(|value| value.provenance == OpaqueIdProvenance::Synthetic) {
            return Some(ExactRoundTripError::SyntheticOpaqueId {
                item_index: None,
                field: field.to_owned(),
            });
        }
    }
    for (item_index, item) in envelope.items.iter().enumerate() {
        for (field, identifier) in [
            ("items[].id", item.id.as_ref()),
            ("items[].call_id", item.call_id.as_ref()),
        ] {
            if identifier.is_some_and(|value| value.provenance == OpaqueIdProvenance::Synthetic) {
                return Some(ExactRoundTripError::SyntheticOpaqueId {
                    item_index: Some(item_index),
                    field: field.to_owned(),
                });
            }
        }
    }
    None
}

fn require_loss(loss: Option<Loss>, operation: MutationKind) -> Result<Loss, IrMutationError> {
    loss.ok_or(IrMutationError::MissingLoss { operation })
}

fn check_index(
    index: usize,
    collection: OrderedCollection,
    len: usize,
) -> Result<(), IrMutationError> {
    if index >= len {
        Err(IrMutationError::IndexOutOfBounds {
            collection,
            index,
            len,
        })
    } else {
        Ok(())
    }
}

fn check_adjacent(
    left: usize,
    right: usize,
    collection: OrderedCollection,
    len: usize,
) -> Result<(), IrMutationError> {
    check_index(left, collection, len)?;
    check_index(right, collection, len)?;
    if left.checked_add(1) != Some(right) {
        return Err(IrMutationError::NonAdjacent {
            collection,
            left,
            right,
        });
    }
    Ok(())
}

fn validate_item(item: &Item, item_index: usize) -> Result<(), IrValidationError> {
    let mut function_calls = 0_usize;
    let mut function_results = 0_usize;
    let mut has_non_function_payload = false;
    for (part_index, part) in item.parts.iter().enumerate() {
        validate_part(part, item_index, part_index)?;
        if let Some(function) = part.function.as_ref() {
            match &function.kind {
                FunctionKind::Call => function_calls += 1,
                FunctionKind::Result => function_results += 1,
                FunctionKind::Unknown(_) => {}
            }
        } else if !matches!(&part.kind, PartKind::Opaque) {
            has_non_function_payload = true;
        }
        let Some(state) = part.opaque.as_ref() else {
            continue;
        };
        if let Err(error) = validate_opaque_state_invariant(state) {
            let field = match error {
                OpaqueStateError::EmptyProvider => "provider",
                OpaqueStateError::EmptyKind => "kind",
            };
            return Err(IrValidationError::InvalidOpaqueState {
                item_index,
                part_index,
                field: field.to_owned(),
            });
        }
    }
    match &item.kind {
        ItemKind::ToolCall => {
            if function_calls != 1 || function_results != 0 || has_non_function_payload {
                return Err(IrValidationError::InvalidItemShape {
                    item_index,
                    reason: "tool_call_requires_one_call_function".to_owned(),
                });
            }
        }
        ItemKind::ToolResult => {
            if function_results != 1 || function_calls != 0 || has_non_function_payload {
                return Err(IrValidationError::InvalidItemShape {
                    item_index,
                    reason: "tool_result_requires_one_result_function".to_owned(),
                });
            }
        }
        ItemKind::Message | ItemKind::Reasoning | ItemKind::Unknown(_) => {
            if function_calls != 0 || function_results != 0 {
                return Err(IrValidationError::InvalidItemShape {
                    item_index,
                    reason: "ordinary_item_cannot_carry_function".to_owned(),
                });
            }
        }
    }
    Ok(())
}

fn validate_part(
    part: &Part,
    item_index: usize,
    part_index: usize,
) -> Result<(), IrValidationError> {
    let invalid_shape = |reason: &'static str| {
        Err(IrValidationError::InvalidPartShape {
            item_index,
            part_index,
            reason: reason.to_owned(),
        })
    };
    match &part.kind {
        PartKind::Text => {
            if part.text.is_none()
                || part.media.is_some()
                || part.function.is_some()
                || part.opaque.is_some()
            {
                return invalid_shape("text_payload");
            }
        }
        PartKind::Media => {
            if part.media.is_none()
                || part.text.is_some()
                || part.function.is_some()
                || part.opaque.is_some()
            {
                return invalid_shape("media_payload");
            }
        }
        PartKind::Function => {
            if part.function.is_none()
                || part.text.is_some()
                || part.media.is_some()
                || part.opaque.is_some()
            {
                return invalid_shape("function_payload");
            }
            if let Some(function) = part.function.as_ref() {
                validate_function(function, item_index, part_index)?;
            }
        }
        PartKind::Opaque => {
            if part.opaque.is_none()
                || part.text.is_some()
                || part.media.is_some()
                || part.function.is_some()
            {
                return invalid_shape("opaque_payload");
            }
        }
        PartKind::Unknown(_) => {
            if part.text.is_some()
                || part.media.is_some()
                || part.function.is_some()
                || part.opaque.is_some()
            {
                return invalid_shape("unknown_payload");
            }
        }
    }
    Ok(())
}

fn validate_function(
    function: &FunctionData,
    item_index: usize,
    part_index: usize,
) -> Result<(), IrValidationError> {
    let invalid = |reason: &'static str| {
        Err(IrValidationError::InvalidFunctionShape {
            item_index,
            part_index,
            reason: reason.to_owned(),
        })
    };
    match &function.kind {
        FunctionKind::Call => {
            let Some(name) = function.name.as_ref() else {
                return invalid("call_name_required");
            };
            if name.is_empty() || function.arguments.is_none() || function.output.is_some() {
                return invalid("call_fields");
            }
        }
        FunctionKind::Result => {
            if function.output.is_none() || function.arguments.is_some() {
                return invalid("result_fields");
            }
        }
        FunctionKind::Unknown(_) => return invalid("unknown_function_kind"),
    }
    Ok(())
}

fn validate_item_merge(left: &Item, right: &Item) -> Result<(), IrMutationError> {
    if left.kind != right.kind || left.role != right.role {
        return Err(IrMutationError::MergeConflict {
            collection: OrderedCollection::Items,
            reason: "kind_or_role".to_owned(),
        });
    }
    if left.id.is_some() || left.call_id.is_some() || right.id.is_some() || right.call_id.is_some()
    {
        return Err(IrMutationError::MergeConflict {
            collection: OrderedCollection::Items,
            reason: "identity".to_owned(),
        });
    }
    if left.raw.is_some() || right.raw.is_some() {
        return Err(IrMutationError::MergeConflict {
            collection: OrderedCollection::Items,
            reason: "raw".to_owned(),
        });
    }
    if left.provenance != right.provenance {
        return Err(IrMutationError::MergeConflict {
            collection: OrderedCollection::Items,
            reason: "provenance".to_owned(),
        });
    }
    if left
        .extensions
        .keys()
        .any(|key| right.extensions.contains_key(key))
    {
        return Err(IrMutationError::MergeConflict {
            collection: OrderedCollection::Items,
            reason: "extension_collision".to_owned(),
        });
    }
    Ok(())
}

fn merge_part_values(left: &Part, right: &Part) -> Result<Part, IrMutationError> {
    if left.kind != right.kind {
        return Err(IrMutationError::MergeConflict {
            collection: OrderedCollection::Parts,
            reason: "kind".to_owned(),
        });
    }
    if left.media.is_some() && right.media.is_some()
        || left.function.is_some() && right.function.is_some()
        || left.opaque.is_some() && right.opaque.is_some()
    {
        return Err(IrMutationError::MergeConflict {
            collection: OrderedCollection::Parts,
            reason: "payload_collision".to_owned(),
        });
    }
    if left
        .extensions
        .keys()
        .any(|key| right.extensions.contains_key(key))
    {
        return Err(IrMutationError::MergeConflict {
            collection: OrderedCollection::Parts,
            reason: "extension_collision".to_owned(),
        });
    }
    let mut merged = left.clone();
    if let (Some(left_text), Some(right_text)) = (&left.text, &right.text) {
        merged.text = Some(format!("{left_text}{right_text}"));
    } else if merged.text.is_none() {
        merged.text = right.text.clone();
    }
    if merged.media.is_none() {
        merged.media = right.media.clone();
    }
    if merged.function.is_none() {
        merged.function = right.function.clone();
    }
    if merged.opaque.is_none() {
        merged.opaque = right.opaque.clone();
    }
    merged.extensions.extend(right.extensions.clone());
    Ok(merged)
}

impl From<IrValidationError> for IrMutationError {
    fn from(error: IrValidationError) -> Self {
        Self::Validation(error)
    }
}

impl fmt::Display for IrMutationError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::MissingLoss { operation } => write!(
                formatter,
                "loss entry required before {operation:?} mutation"
            ),
            Self::IndexOutOfBounds {
                collection,
                index,
                len,
            } => write!(
                formatter,
                "{collection:?} index {index} is outside length {len}"
            ),
            Self::NonAdjacent {
                collection,
                left,
                right,
            } => write!(
                formatter,
                "{collection:?} merge requires adjacent indices, got {left} and {right}"
            ),
            Self::MergeConflict { collection, reason } => {
                write!(formatter, "cannot merge {collection:?}: {reason}")
            }
            Self::Validation(error) => error.fmt(formatter),
        }
    }
}

impl Error for IrMutationError {}

impl fmt::Display for IrValidationError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::MissingToolCallId { item_index } => {
                write!(formatter, "tool item {item_index} has no call id")
            }
            Self::OrphanToolResult {
                item_index,
                call_id,
            } => write!(
                formatter,
                "tool result {item_index} has orphan call id {call_id}"
            ),
            Self::DuplicateToolCallId {
                first_item_index,
                second_item_index,
                call_id,
            } => write!(
                formatter,
                "tool call id {call_id} is reused by items {first_item_index} and {second_item_index}"
            ),
            Self::DuplicateToolResult {
                first_item_index,
                second_item_index,
                call_id,
            } => write!(
                formatter,
                "tool result call id {call_id} is reused by items {first_item_index} and {second_item_index}"
            ),
            Self::EmptyOpaqueId { item_index, field } => {
                write!(
                    formatter,
                    "item {item_index} has empty opaque id field {field}"
                )
            }
            Self::EmptyStateId { field } => {
                write!(formatter, "state field {field} has an empty opaque id")
            }
            Self::InvalidPartShape {
                item_index,
                part_index,
                reason,
            } => write!(
                formatter,
                "part at item {item_index}, part {part_index} has invalid shape: {reason}"
            ),
            Self::InvalidFunctionShape {
                item_index,
                part_index,
                reason,
            } => write!(
                formatter,
                "function at item {item_index}, part {part_index} has invalid shape: {reason}"
            ),
            Self::InvalidItemShape { item_index, reason } => write!(
                formatter,
                "item {item_index} has invalid function relationship: {reason}"
            ),
            Self::InvalidOpaqueState {
                item_index,
                part_index,
                field,
            } => write!(
                formatter,
                "opaque state at item {item_index}, part {part_index} has empty {field}"
            ),
        }
    }
}

impl Error for IrValidationError {}

impl fmt::Display for ExactRoundTripError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::LossesPresent { losses } => {
                write!(
                    formatter,
                    "exact round trip has {} loss entries",
                    losses.len()
                )
            }
            Self::Validation(error) => error.fmt(formatter),
            Self::SyntheticOpaqueState {
                item_index,
                part_index,
            } => write!(
                formatter,
                "synthetic opaque state at item {item_index}, part {part_index} is not exact"
            ),
            Self::SyntheticOpaqueId { item_index, field } => write!(
                formatter,
                "synthetic opaque id in {field} at item {item_index:?} is not exact"
            ),
            Self::UnmodeledField { path } => {
                write!(
                    formatter,
                    "unmodeled field at {path} prevents exact round trip"
                )
            }
        }
    }
}

