/// Provenance attached to every ordered item.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Provenance {
    /// Protocol which originally supplied the item.
    pub source: Protocol,
    /// Safe source path, such as `messages[2].content[1]`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub source_path: Option<String>,
    /// Converter or adapter identifier which last touched the item.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub converter: Option<String>,
    /// Provider fields not yet modeled by the IR.
    #[serde(flatten)]
    #[serde(default)]
    pub extensions: ExtensionBag,
}

impl Provenance {
    /// Creates provenance for an item received from `source`.
    #[must_use]
    pub fn new(source: Protocol) -> Self {
        Self {
            source,
            source_path: None,
            converter: None,
            extensions: ExtensionBag::new(),
        }
    }
}

