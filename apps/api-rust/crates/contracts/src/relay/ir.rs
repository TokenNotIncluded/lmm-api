//! Loss-aware, ordered provider-neutral relay intermediate representation.
//!
//! The IR deliberately keeps `Vec` order visible in its public data model.
//! Converters may remove, merge, or reorder values only through the mutation
//! methods on [`Envelope`], each of which requires a structured [`Loss`].
//! Unknown provider fields are retained in [`ExtensionBag`] values instead of
//! being discarded while decoding.

use std::{collections::BTreeMap, error::Error, fmt};

use serde::{Deserialize, Deserializer, Serialize, Serializer};

use super::{
    JsonData, Loss, LossLedger, OpaqueProviderState, OpaqueStateProvenance, Protocol, Role,
};

/// Provider or gateway extension fields which are not part of the stable IR.
///
/// A sorted map gives deterministic serialization while retaining the complete
/// value of an unknown field.  Extension values must not contain request text
/// merely for diagnostic convenience; callers should store only protocol data.
pub type ExtensionBag = BTreeMap<String, JsonData>;

/// Whether an opaque identifier came from a provider or was generated by a
/// compatibility layer.
///
/// This marker is deliberately explicit.  The IR never guesses provenance
/// from the identifier's spelling, because a synthetic value can be
/// byte-for-byte identical to an authentic value.
#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum OpaqueIdProvenance {
    /// Bytes received from the source protocol.
    Authentic,
    /// A value generated by an adapter for compatibility.
    Synthetic,
}

/// An identifier carried opaquely between provider boundaries.
///
/// The IR never parses, normalizes, generates, or otherwise interprets the
/// string inside this type.  This is important for provider call identifiers
/// whose exact bytes are required by a later tool result.  The source and
/// provenance are kept alongside the value so exact-round-trip checks do not
/// have to infer them from a string.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
pub struct OpaqueId {
    /// Identifier bytes as supplied by the source.
    pub value: String,
    /// Whether the value is authentic source data or adapter-generated.
    pub provenance: OpaqueIdProvenance,
    /// Protocol which owns the identifier.
    pub source: Protocol,
}

impl OpaqueId {
    /// Creates an authentic identifier without changing its contents.
    #[must_use]
    pub fn authentic(value: impl Into<String>, source: Protocol) -> Self {
        Self {
            value: value.into(),
            provenance: OpaqueIdProvenance::Authentic,
            source,
        }
    }

    /// Creates an adapter-generated identifier without changing its contents.
    #[must_use]
    pub fn synthetic(value: impl Into<String>, source: Protocol) -> Self {
        Self {
            value: value.into(),
            provenance: OpaqueIdProvenance::Synthetic,
            source,
        }
    }

    /// Borrows the identifier exactly as supplied.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.value
    }

    /// Returns the owned identifier without normalization.
    #[must_use]
    pub fn into_string(self) -> String {
        self.value
    }

    /// Returns whether this identifier has no bytes.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.value.is_empty()
    }

    /// Returns whether this identifier came from the source protocol.
    #[must_use]
    pub fn provenance(&self) -> OpaqueIdProvenance {
        self.provenance
    }

    /// Returns the protocol which supplied or owns this identifier.
    #[must_use]
    pub fn source(&self) -> Protocol {
        self.source
    }
}

impl fmt::Display for OpaqueId {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(self.as_str())
    }
}

/// The semantic kind of an ordered IR item.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum ItemKind {
    /// A normal conversational message.
    Message,
    /// A function/tool invocation emitted by the model.
    ToolCall,
    /// A function/tool result supplied by the caller.
    ToolResult,
    /// A provider reasoning item which is not ordinary visible text.
    Reasoning,
    /// A provider-defined item kind retained by name.
    Unknown(String),
}

impl ItemKind {
    /// Returns the stable wire spelling, preserving an unknown spelling.
    #[must_use]
    pub fn as_str(&self) -> &str {
        match self {
            Self::Message => "message",
            Self::ToolCall => "tool_call",
            Self::ToolResult => "tool_result",
            Self::Reasoning => "reasoning",
            Self::Unknown(value) => value,
        }
    }
}

impl Serialize for ItemKind {
    fn serialize<S>(&self, serializer: S) -> Result<S::Ok, S::Error>
    where
        S: Serializer,
    {
        serializer.serialize_str(self.as_str())
    }
}

impl<'de> Deserialize<'de> for ItemKind {
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: Deserializer<'de>,
    {
        let value = String::deserialize(deserializer)?;
        Ok(match value.as_str() {
            "message" => Self::Message,
            "tool_call" => Self::ToolCall,
            "tool_result" => Self::ToolResult,
            "reasoning" => Self::Reasoning,
            _ => Self::Unknown(value),
        })
    }
}

