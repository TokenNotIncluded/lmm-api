/// One ordered semantic item in an [`Envelope`].
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Item {
    /// Item semantic kind.
    pub kind: ItemKind,
    /// Provider-neutral role.
    pub role: Role,
    /// Opaque item identifier, if supplied.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub id: Option<OpaqueId>,
    /// Function call identifier used by a tool result.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub call_id: Option<OpaqueId>,
    /// Ordered content Parts; order is semantic and never rewritten by IR.
    #[serde(default)]
    parts: Vec<Part>,
    /// Source provenance for this item.
    pub provenance: Provenance,
    /// Original structured item, retained when no typed representation exists.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub raw: Option<JsonData>,
    /// Unknown item fields retained for round trips.
    #[serde(flatten)]
    #[serde(default)]
    pub extensions: ExtensionBag,
}

impl Item {
    /// Creates an item with an empty ordered Part list.
    #[must_use]
    pub fn new(kind: ItemKind, role: Role, provenance: Provenance) -> Self {
        Self {
            kind,
            role,
            id: None,
            call_id: None,
            parts: Vec::new(),
            provenance,
            raw: None,
            extensions: ExtensionBag::new(),
        }
    }

    /// Creates a tool-call item whose opaque call id is preserved exactly.
    #[must_use]
    pub fn tool_call(call_id: OpaqueId, parts: Vec<Part>, provenance: Provenance) -> Self {
        let mut item = Self::new(ItemKind::ToolCall, Role::Assistant, provenance);
        item.call_id = Some(call_id);
        item.parts = parts;
        item
    }

    /// Creates a tool-result item linked to a prior tool call.
    #[must_use]
    pub fn tool_result(call_id: OpaqueId, parts: Vec<Part>, provenance: Provenance) -> Self {
        let mut item = Self::new(ItemKind::ToolResult, Role::Tool, provenance);
        item.call_id = Some(call_id);
        item.parts = parts;
        item
    }

    /// Returns the ordered Part slice without exposing mutable reordering.
    #[must_use]
    pub fn ordered_parts(&self) -> &[Part] {
        &self.parts
    }

    /// Appends a Part while preserving all existing Part order.
    pub fn push_part(&mut self, part: Part) {
        self.parts.push(part);
    }
}

