export interface HeroSmsPhoneNumberParts {
  callingCode: string
  subscriberNumber: string
  e164: string
  display: string
  masked?: boolean
}

export function resolveHeroSmsPhoneNumber(
  value: string | null | undefined
): HeroSmsPhoneNumberParts | null {
  const raw = String(value ?? '').trim()
  if (/^•{4}(?:\s+\d{4})?$/.test(raw)) {
    return {
      callingCode: '',
      subscriberNumber: raw,
      e164: raw,
      display: raw,
      masked: true,
    }
  }

  let digits = raw.replaceAll(/\D/g, '')
  if (digits.startsWith('00')) digits = digits.slice(2)
  if (!digits) return null

  const callingCode =
    HERO_SMS_DIALING_PREFIXES.find((prefix) => digits.startsWith(prefix)) ?? ''
  const subscriberNumber = callingCode
    ? digits.slice(callingCode.length)
    : digits
  const e164 = `+${digits}`
  return {
    callingCode,
    subscriberNumber,
    e164,
    display:
      callingCode && subscriberNumber
        ? `+${callingCode} ${subscriberNumber}`
        : e164,
  }
}
