export type MarketConnectionCopyKey = keyof typeof rows
export const marketConnectionTranslations = Object.fromEntries(
  languages.map((language, index) => [
    language,
    Object.fromEntries(
      Object.entries(rows).map(([key, values]) => [key, values[index]])
    ),
  ])
) as Record<(typeof languages)[number], Record<MarketConnectionCopyKey, string>>

const registered = new WeakSet<i18n>()
export function registerMarketConnectionTranslations(instance: i18n): void {
  if (registered.has(instance)) return
  for (const language of languages) {
    instance.addResourceBundle(
      language,
      marketConnectionNamespace,
      marketConnectionTranslations[language],
      true,
      false
    )
  }
  registered.add(instance)
}
