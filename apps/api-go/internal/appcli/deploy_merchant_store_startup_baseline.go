// One bounded READ ONLY transaction on the actual effective business DSN.
// Checking every remaining client backend in this database also fails closed
// for unclassified workers, including clients with a different SQL role.
func captureMerchantStartupDatabase(ctx context.Context, values map[string]string) (productionMerchantStartupDatabase, error) {
	var d productionMerchantStartupDatabase
	dsn, err := productionDatabaseURL(values)
	if err != nil {
		return d, err
	}
	if err := verifyExistingSchemaLogDatabase(values, dsn); err != nil {
		return d, err
	}
	if err := rejectMerchantStoreAmbientPGEnvironment(values); err != nil {
		return d, err
	}
	parsed, err := url.Parse(dsn)
	if err != nil || parsed.Fragment != "" {
		return d, errors.New("startup capture business PostgreSQL configuration is invalid")
	}
	query, err := url.ParseQuery(parsed.RawQuery)
	if err != nil {
		return d, errors.New("startup capture business PostgreSQL configuration is invalid")
	}
	options, err := productionPostgresRuntimeOptions(query, values)
	if err != nil {
		return d, err
	}
	config, err := pgx.ParseConfig(dsn)
	if err != nil {
		return d, errors.New("startup capture business PostgreSQL configuration is invalid")
	}
	config.RuntimeParams["options"] = options
	config.ConnectTimeout = 10 * time.Second
	config.RuntimeParams["default_transaction_read_only"] = "on"
	config.RuntimeParams["statement_timeout"] = "15000"
	config.RuntimeParams["lock_timeout"] = "3000"
	config.RuntimeParams["application_name"] = "lmm-startup-baseline-capture"
	conn, err := pgx.ConnectConfig(ctx, config)
	if err != nil {
		return d, errors.New("startup capture actual business connection unavailable")
	}
	defer conn.Close(context.Background())
	tx, err := conn.BeginTx(ctx, pgx.TxOptions{IsoLevel: pgx.RepeatableRead, AccessMode: pgx.ReadOnly})
	if err != nil {
		return d, errors.New("startup capture read-only transaction unavailable")
	}
	defer tx.Rollback(context.Background())
	var sessionRole, readonly string
	err = tx.QueryRow(ctx, `SELECT (SELECT system_identifier::text FROM pg_catalog.pg_control_system()),current_database(),
(SELECT oid::bigint FROM pg_catalog.pg_database WHERE datname=current_database()),current_schema(),
(SELECT oid::bigint FROM pg_catalog.pg_namespace WHERE nspname=current_schema()),current_user,session_user,
current_setting('transaction_read_only'),(SELECT count(*)::int FROM pg_catalog.pg_stat_activity WHERE datid=(SELECT oid FROM pg_catalog.pg_database WHERE datname=current_database()) AND backend_type='client backend' AND pid<>pg_backend_pid())`).Scan(&d.SystemIdentifier, &d.Database, &d.DatabaseOID, &d.Schema, &d.SchemaOID, &d.Role, &sessionRole, &readonly, &d.OtherClients)
	if err != nil || readonly != "on" || sessionRole != d.Role || !isDatabaseSchema(d.Schema) {
		return d, errors.New("startup capture physical database/business role/read-only identity unavailable")
	}
	err = tx.QueryRow(ctx, `SELECT COALESCE(array_agg(value ORDER BY value),ARRAY[]::text[]) FROM "`+d.Schema+`".options WHERE key='MerchantStoreMinimumWriterCapability'`).Scan(&d.FloorValues)
	if err != nil {
		return d, errors.New("startup capture gate Option unavailable")
	}
	err = tx.QueryRow(ctx, `SELECT EXISTS(SELECT 1 FROM "`+d.Schema+`".options WHERE `+deploymentfence.PostgreSQLPresencePredicate+`)`).Scan(&d.ReservedOwners)
	if err != nil {
		return d, errors.New("startup capture reserved deployment ownership unavailable")
	}
	err = tx.QueryRow(ctx, `SELECT
 (SELECT count(*) FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname=$1 AND c.relkind IN ('r','p') AND starts_with(c.relname,'merchant_store_'))=15
	 AND NOT EXISTS(SELECT 1 FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname=$1 AND c.relname='merchant_store_variants')
 AND NOT EXISTS(SELECT 1 FROM pg_catalog.pg_attribute a JOIN pg_catalog.pg_class c ON c.oid=a.attrelid JOIN pg_catalog.pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname=$1 AND c.relname IN ('merchant_store_stocks','merchant_store_orders') AND a.attname='variant_id' AND a.attnum>0 AND NOT a.attisdropped)`, d.Schema).Scan(&d.PreVariant)
	if err != nil {
		return d, errors.New("startup capture merchant schema inventory unavailable")
	}
	return d, nil
}

