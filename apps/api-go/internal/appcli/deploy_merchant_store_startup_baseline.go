func merchantStartupAdmissionBody(id string) string { return merchantStartupAdmissionKind + ":" + id }

func merchantStartupAdmissionBarrier(original []byte, id string) ([]byte, error) {
	if !productionIDPattern.MatchString(id) || bytes.Contains(original, []byte(merchantStartupAdmissionKind)) {
		return nil, errors.New("startup admission identity/original config is invalid")
	}
	if _, err := billingBarrierBody(original, merchantStartupAdmissionBody(id)); err != nil {
		return nil, err
	}
	return append([]byte("add_header Retry-After '60' always;\nadd_header X-LMM-Startup-Baseline '"+id+"' always;\nreturn 503 '"+merchantStartupAdmissionBody(id)+"';\n"), original...), nil
}

// Probe this origin's own TLS listener, never one DNS-selected origin. SNI,
// Host, status, canonical headers and body are fixed and enter the capture.
func (runtime *productionRuntime) probeMerchantStartupAdmission(ctx context.Context, id string) error {
	u, err := url.Parse(runtime.paths.PublicBaseURL)
	if err != nil || u.Scheme != "https" || u.Host != "api.lmm.best" || u.Path != "" || u.User != nil {
		return errors.New("startup admission requires the canonical production origin")
	}
	for _, route := range []string{"/api/status", "/api/user/self", "/v1/models"} {
		out, err := runtime.runner.Run(ctx, productionCommand{Name: "/usr/bin/curl", Args: []string{"--silent", "--show-error", "--include", "--max-time", "5", "--noproxy", "*", "--connect-to", "api.lmm.best:443:127.0.0.1:443", "https://api.lmm.best" + route}, Env: []string{"PATH=/usr/bin:/bin", "LANG=C", "LC_ALL=C"}, Timeout: 7 * time.Second, OutputLimit: 32768})
		if err != nil {
			return errors.New("origin-specific startup admission probe failed")
		}
		parts := bytes.SplitN(out, []byte("\r\n\r\n"), 2)
		if len(parts) != 2 || string(parts[1]) != merchantStartupAdmissionBody(id) {
			return errors.New("startup admission body differs")
		}
		lines := strings.Split(string(parts[0]), "\r\n")
		status := strings.Fields(lines[0])
		if len(status) < 2 || status[1] != "503" {
			return errors.New("startup admission status differs")
		}
		headers := map[string]string{}
		for _, line := range lines[1:] {
			k, v, ok := strings.Cut(line, ":")
			if !ok {
				return errors.New("startup admission headers malformed")
			}
			k = strings.ToLower(k)
			if _, duplicate := headers[k]; duplicate {
				return errors.New("startup admission duplicated header")
			}
			headers[k] = strings.TrimSpace(v)
		}
		if headers["retry-after"] != "60" || headers["x-lmm-startup-baseline"] != id {
			return errors.New("startup admission canonical headers differ")
		}
	}
	return nil
}

// The parser delegates to this separate authority instead of manufacturing a
// GoChanged ordinary plan. Commands never accept paths for closure evidence.
func runProductionMerchantStartupBaseline(args []string, stdout, stderr io.Writer) int {
	if len(args) == 0 {
		return ExitUsage
	}
	flags := flag.NewFlagSet("production writer-capsule "+args[0], flag.ContinueOnError)
	flags.SetOutput(stderr)
	id := flags.String("id", "", "fixed first-conversion identity")
	repo := flags.String("repo", "", "clean canonical source checkout for official artifact verification")
	predecessor := flags.String("predecessor-id", "", "previous actually confirmed startup baseline identity")
	if flags.Parse(args[1:]) != nil || flags.NArg() != 0 || !productionIDPattern.MatchString(*id) {
		return ExitUsage
	}
	runtime := defaultProductionRuntime()
	if runtime.effectiveUID() != 0 {
		return ExitError
	}
	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Minute)
	defer cancel()
	err := runtime.runMerchantStartupBaseline(ctx, args[0], *id, *repo, *predecessor, stdout)
	if err != nil {
		_, _ = fmt.Fprintf(stderr, "%s startup-baseline: %v\n", DeployProgramName, err)
		return ExitError
	}
	return ExitOK
}

