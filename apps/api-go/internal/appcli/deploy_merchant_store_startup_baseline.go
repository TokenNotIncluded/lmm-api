func (runtime *productionRuntime) startupBaselineNewFile(path string, value any) error {
	raw, err := merchantStartupJSON(value)
	if err != nil {
		return err
	}
	return runtime.startupBaselineNewBytes(path, raw)
}

func (runtime *productionRuntime) startupBaselineNewBytes(path string, raw []byte) error {
	if len(raw) == 0 || len(raw) > 1<<20 {
		return errors.New("startup baseline evidence exceeds bounded file size")
	}
	if err := runtime.merchantStorePrivateDirectory(filepath.Dir(path), false); err != nil {
		return err
	}
	f, err := os.OpenFile(path, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0600)
	if err != nil {
		return errors.New("startup baseline evidence already exists or cannot be created")
	}
	_, err = f.Write(raw)
	if err == nil {
		err = f.Sync()
	}
	closeErr := f.Close()
	if err == nil {
		err = closeErr
	}
	return err
}

func (runtime *productionRuntime) startupBaselineRead(path string, value any) ([]byte, error) {
	raw, err := runtime.readExistingSchemaSealedFile(path, true)
	if err != nil || len(raw) > 32768 || !merchantStoreUniqueJSON(raw) {
		return nil, errors.New("startup baseline evidence is absent/unsafe/ambiguous")
	}
	d := json.NewDecoder(bytes.NewReader(raw))
	d.DisallowUnknownFields()
	if d.Decode(value) != nil || d.Decode(&struct{}{}) != io.EOF {
		return nil, errors.New("startup baseline evidence JSON invalid")
	}
	canonical, err := merchantStartupJSON(value)
	if err != nil || !bytes.Equal(canonical, raw) {
		return nil, errors.New("startup baseline evidence noncanonical")
	}
	return raw, nil
}

func (runtime *productionRuntime) startupBaselineProvider(ctx context.Context, root, repo, role string) (productionReleasePackagePlan, error) {
	var zero productionReleasePackagePlan
	if role != "candidate" && role != "preactivation" {
		return zero, errors.New("startup provider role invalid")
	}
	if clean, err := cleanAbsoluteNonRoot(repo); err != nil || clean != repo {
		return zero, errors.New("startup baseline requires canonical source checkout")
	}
	if err := validateBuildRepository(repo); err != nil {
		return zero, err
	}
	for _, kind := range []string{"pkg.tar.zst", "release.tar.gz", "sigstore.json"} {
		if err := runtime.merchantStoreCapsuleFile(filepath.Join(root, merchantStoreCapsuleAsset(role, kind)), 0600); err != nil {
			return zero, err
		}
	}
	r := productionReleaseRuntime{runner: merchantStartupVerificationRunner{runtime.runner}, now: runtime.now}
	p, err := r.verifyStartupBaselinePackageEvidence(ctx, repo, root, runtime, filepath.Join(root, merchantStoreCapsuleAsset(role, "pkg.tar.zst")), filepath.Join(root, merchantStoreCapsuleAsset(role, "release.tar.gz")), filepath.Join(root, merchantStoreCapsuleAsset(role, "sigstore.json")))
	if err != nil {
		return zero, err
	}
	return merchantStoreCapsuleProjection(p, role), nil
}

