func (b *productionMerchantStartupBaseline) writerIdentity(host string) *productionMerchantStoreWriterContract {
	if b == nil || len(b.Closure.Hosts) == 0 {
		return nil
	}
	var h productionMerchantStartupHostCapture
	for _, captured := range b.Closure.Hosts {
		if captured.Host == host {
			h = captured
		}
	}
	if h.Host == "" {
		return nil
	}
	return &productionMerchantStoreWriterContract{Format: 1, RequiredCapability: b.RequiredCapability,
		SystemIdentifier: h.Schema.SystemIdentifier, Database: h.Schema.Database, DatabaseOID: h.Schema.DatabaseOID,
		Schema: h.Schema.Schema, SchemaOID: h.Schema.SchemaOID, Role: b.Role,
		StartupSHA256: h.Schema.StartupSHA256, SignedUnitSHA256: h.Schema.SignedUnitSHA256,
		RecoveryPolicy: "startup-only", Candidate: productionMerchantStoreWriterTarget{
			Capability: b.Provider.MerchantStoreWriterCapability, PackageSHA256: b.Provider.PackageSHA256,
			PayloadSHA256: b.Provider.PayloadSHA256, SourceRevision: b.Provider.GitRevision,
			ReleaseAssetSHA256: b.Provider.ReleaseAssetSHA256, StatusSHA256: b.StatusSHA256}}
}

func validateMerchantStartupHostCapture(h productionMerchantStartupHostCapture, id, provider string) error {
	if h.Format != 1 || h.DeploymentID != id || h.ProviderSHA256 != provider || !merchantStoreFenceHostPattern.MatchString(h.Host) ||
		!productionSHA256Pattern.MatchString(h.AdmissionSHA256) || !productionSHA256Pattern.MatchString(h.AdmissionBodySHA256) ||
		h.NginxPID <= 1 || !existingSchemaInvocationPattern.MatchString(h.NginxInvocationID) ||
		!productionSHA256Pattern.MatchString(h.NginxGenerationSHA256) || !productionSHA256Pattern.MatchString(h.CloseSHA256) ||
		!productionSHA256Pattern.MatchString(h.LegacyStartupSHA256) || !productionSHA256Pattern.MatchString(h.StatusSHA256) ||
		!productionSHA256Pattern.MatchString(h.StartupBarrierSHA256) || h.LegacyPID <= 1 ||
		!existingSchemaInvocationPattern.MatchString(h.LegacyInvocationID) || !productionSHA256Pattern.MatchString(h.LegacyPayloadSHA256) ||
		(h.GateBefore != "MISSING_PRE_VARIANT" && !strings.HasPrefix(h.GateBefore, "CONFIRMED_BASELINE:")) || h.OtherBusinessClients != 0 || !validMerchantStoreCapability(h.RequiredCapability) {
		return errors.New("startup baseline lacks actual closed pre-activation host evidence")
	}
	if h.StartupBarrierKind != "sealed-pending-hook" {
		return errors.New("startup baseline lacks a persistent fail-closed startup barrier")
	}
	if h.AdmissionBodySHA256 != startupContentSHA256([]byte(merchantStartupAdmissionKind+":"+id)) {
		return errors.New("startup baseline admission identity differs")
	}
	return validateProductionExistingSchemaContract(&h.Schema)
}

func validateMerchantStartupBaseline(b *productionMerchantStartupBaseline) error {
	if b == nil || b.Kind != merchantStartupBaselineKind || b.PredecessorSHA256 != "" && !productionSHA256Pattern.MatchString(b.PredecessorSHA256) ||
		b.Closure.Format != 1 || !productionIDPattern.MatchString(b.Closure.DeploymentID) ||
		b.Closure.ProviderSHA256 != b.Provider.PayloadSHA256 || len(b.Closure.Hosts) != len(merchantStartupOrigins) ||
		!productionSHA256Pattern.MatchString(b.StatusSHA256) {
		return errors.New("startup baseline authority is incomplete or has an unsupported predecessor")
	}
	for i, h := range b.Closure.Hosts {
		if h.Host != merchantStartupOrigins[i].Host || h.Role != b.Role || h.RequiredCapability != b.RequiredCapability || h.StatusSHA256 != b.StatusSHA256 {
			return errors.New("startup baseline omitted/reordered an origin or its actual role/floor differs")
		}
		if err := validateMerchantStartupHostCapture(h, b.Closure.DeploymentID, b.Provider.PayloadSHA256); err != nil {
			return err
		}
		if b.PredecessorSHA256 == "" && (h.GateBefore != "MISSING_PRE_VARIANT" || b.RequiredCapability != 1) ||
			b.PredecessorSHA256 != "" && h.GateBefore != "CONFIRMED_BASELINE:"+b.PredecessorSHA256 {
			return errors.New("startup baseline before/after gate provenance differs")
		}
		left, right := h.Schema, b.Closure.Hosts[0].Schema
		left.StartupSHA256, right.StartupSHA256 = "", ""
		if left != right {
			return errors.New("startup baseline origins do not bind the same physical schema")
		}
	}
	identity := b.writerIdentity(merchantStartupOrigins[0].Host)
	if err := validateMerchantStoreWriterHostIdentity(identity); err != nil {
		return err
	}
	if err := validateMerchantStoreWriterTarget(identity.Candidate, identity.RequiredCapability); err != nil {
		return err
	}
	p := b.Provider
	version, err := packageReleaseVersion(p.Version)
	if err != nil || p.Name != productionAURPackageName || p.Identity != p.Name+" "+p.Version || p.Workflow != "release-go.yml" || p.ReleaseTag != "go-v"+version ||
		!productionContractPattern.MatchString(p.ContractRevision) || !productionSHA256Pattern.MatchString(p.SignatureBundleSHA256) ||
		p.PackagePath != merchantStoreCapsuleAsset("candidate", "pkg.tar.zst") || p.ReleaseAsset != merchantStoreCapsuleAsset("candidate", "release.tar.gz") ||
		p.SignatureBundle != merchantStoreCapsuleAsset("candidate", "sigstore.json") {
		return errors.New("startup baseline provider is not one exact official artifact tuple")
	}
	return nil
}

func validateMerchantStartupBaselineCapsule(c productionMerchantStoreCapsule, paths productionPaths) error {
	if c.Format != 2 || c.Writer != nil || c.Candidate != (productionReleasePackagePlan{}) || c.Rollback != (productionReleasePackagePlan{}) || len(c.SourceFiles) != 0 ||
		!productionIDPattern.MatchString(c.DeploymentID) || c.Root != merchantStoreCapsuleRoot(paths, c.DeploymentID) ||
		c.Service != "lmm-api.service" || c.Service != paths.Service || c.Binary != paths.InstalledBinary || c.ConfigDir != paths.ConfigDir ||
		c.StartupPolicy != "per-start" || c.SchemaMode != productionSchemaModeVerifyExisting || !productionSHA256Pattern.MatchString(c.ControllerPlanSHA256) {
		return errors.New("startup baseline cannot contain an ordinary provider pair or deployment policy")
	}
	if err := validateMerchantStartupBaseline(c.Baseline); err != nil {
		return err
	}
	if c.ControllerPlanSHA256 != merchantStartupAuthoritySHA(c.Baseline) {
		return errors.New("startup baseline authority digest differs from the actual canonical closure")
	}
	if c.DeploymentID != c.Baseline.Closure.DeploymentID || validateProductionExistingSchemaContract(c.ExistingSchemaContract) != nil {
		return errors.New("startup baseline schema/identity is incomplete")
	}
	for _, h := range c.Baseline.Closure.Hosts {
		if h.Host == c.Host {
			if h.Schema != *c.ExistingSchemaContract {
				return errors.New("startup baseline host startup/schema differs")
			}
			return nil
		}
	}
	return errors.New("startup baseline is not for a captured origin")
}

func merchantStartupAuthoritySHA(b *productionMerchantStartupBaseline) string {
	body, err := json.Marshal(b)
	if err != nil {
		return ""
	}
	return startupContentSHA256(body)
}

