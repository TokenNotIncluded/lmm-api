// The legacy unit is not made verify-only by pretending its defaults changed.
// This captures its real ordered private files and compares the active process.
func (runtime *productionRuntime) startupBaselineLegacyValues(ctx context.Context, loaded map[string]string, pid int) (map[string]string, string, error) {
	if loaded["PassEnvironment"] != "" || loaded["UnsetEnvironment"] != "" {
		return nil, "", errors.New("legacy startup has unchecked environment overrides")
	}
	values, err := parseExistingSchemaLoadedEnvironment(loaded["Environment"])
	if err != nil {
		return nil, "", err
	}
	commands, err := verifyExistingSchemaSealedCommands(loaded, runtime.paths.InstalledBinary)
	if err != nil {
		return nil, "", err
	}
	unit, err := runtime.readExistingSchemaSealedFile(loaded["FragmentPath"], false)
	if err != nil {
		return nil, "", err
	}
	snapshot := existingSchemaStartupSnapshot{Environment: map[string]string{}, FragmentPath: loaded["FragmentPath"], UnitSHA256: startupContentSHA256(unit), Commands: commands}
	for k, v := range values {
		snapshot.Environment[k] = v
	}
	seen := map[string]bool{}
	for i, row := range strings.Split(loaded["EnvironmentFiles"], "\n") {
		m := existingSchemaEnvironmentFilePattern.FindStringSubmatch(row)
		if m == nil || seen[m[1]] || i == 0 && m[1] != filepath.Join(runtime.paths.ConfigDir, "lmm-api-go.env") || i >= 16 {
			return nil, "", errors.New("legacy ordered environment closure invalid")
		}
		seen[m[1]] = true
		raw, err := runtime.readExistingSchemaSealedFile(m[1], true)
		if err != nil {
			return nil, "", err
		}
		entries, err := parseProductionEnvironment(raw)
		if err != nil {
			return nil, "", errors.New("legacy environment malformed")
		}
		for k, v := range entries {
			values[k] = v
		}
		snapshot.Files = append(snapshot.Files, existingSchemaEnvironmentFile{Path: m[1], IgnoreErrors: m[2] == "yes", SHA256: startupContentSHA256(raw)})
	}
	dsn, err := productionDatabaseURL(values)
	if err != nil {
		return nil, "", err
	}
	if err := verifyExistingSchemaLogDatabase(values, dsn); err != nil {
		return nil, "", err
	}
	raw, err := os.ReadFile(filepath.Join("/proc", strconv.Itoa(pid), "environ"))
	if err != nil || len(raw) > 1<<20 {
		return nil, "", errors.New("legacy actual process environment unavailable")
	}
	process := map[string]string{}
	for _, row := range bytes.Split(raw, []byte{0}) {
		if len(row) == 0 {
			continue
		}
		k, v, ok := strings.Cut(string(row), "=")
		if !ok || !productionEnvironmentKeyPattern.MatchString(k) {
			return nil, "", errors.New("legacy process environment malformed")
		}
		if _, exists := process[k]; exists {
			return nil, "", errors.New("legacy process environment duplicate")
		}
		process[k] = v
	}
	actual, err := productionDatabaseURL(process)
	if err != nil || actual != dsn || process["PGOPTIONS"] != values["PGOPTIONS"] || verifyExistingSchemaLogDatabase(process, actual) != nil {
		return nil, "", errors.New("legacy actual process database differs from effective startup")
	}
	for _, key := range existingSchemaFinancialEnvironment {
		if process[key] != "" || values[key] != "" {
			return nil, "", errors.New("legacy startup is under financial maintenance")
		}
	}
	encoded, err := json.Marshal(snapshot)
	return values, startupContentSHA256(encoded), err
}

func (runtime *productionRuntime) startupBaselineAdmission(ctx context.Context, id, expected string) (int, string, string, error) {
	path := filepath.Join(runtime.paths.NginxRoot, "lmm-api-locations.conf")
	raw, err := runtime.readExistingSchemaSealedFile(path, false)
	if err != nil || startupContentSHA256(raw) != expected {
		return 0, "", "", errors.New("startup persistent admission bytes changed")
	}
	before, err := runtime.billingUnitState(ctx, "nginx.service")
	pid, parseErr := strconv.Atoi(before["MainPID"])
	if err != nil || parseErr != nil || pid <= 1 || before["ActiveState"] != "active" || before["SubState"] != "running" || !existingSchemaInvocationPattern.MatchString(before["InvocationID"]) {
		return 0, "", "", errors.New("startup nginx generation unavailable")
	}
	childrenPath := filepath.Join("/proc", strconv.Itoa(pid), "task", strconv.Itoa(pid), "children")
	children, err := os.ReadFile(childrenPath)
	if err != nil || len(strings.Fields(string(children))) == 0 {
		return 0, "", "", errors.New("startup nginx live worker generation unavailable")
	}
	if err := runtime.probeMerchantStartupAdmission(ctx, id); err != nil {
		return 0, "", "", err
	}
	n, err := countBillingConnections()
	if err != nil || n != 0 {
		return 0, "", "", errors.New("startup backend still has accepted sockets")
	}
	after, err := runtime.billingUnitState(ctx, "nginx.service")
	afterChildren, childErr := os.ReadFile(childrenPath)
	current, fileErr := runtime.readExistingSchemaSealedFile(path, false)
	if err != nil || childErr != nil || fileErr != nil || before["MainPID"] != after["MainPID"] || before["InvocationID"] != after["InvocationID"] || after["ActiveState"] != "active" || !bytes.Equal(children, afterChildren) || !bytes.Equal(raw, current) {
		return 0, "", "", errors.New("startup nginx loaded generation changed during direct-origin proof")
	}
	return pid, before["InvocationID"], startupContentSHA256(children), nil
}

