func (runtime *productionRuntime) startupBaselineConfirmed(id string) (productionMerchantStoreCapsule, string, error) {
	var empty productionMerchantStoreCapsule
	root, err := runtime.startupBaselineRoot(id)
	if err != nil {
		return empty, "", err
	}
	var receipt productionMerchantStartupConfirmation
	if _, err := runtime.startupBaselineRead(filepath.Join(root, "state", "baseline-confirmed.json"), &receipt); err != nil {
		return empty, "", err
	}
	c, err := runtime.loadMerchantStoreCapsule(filepath.Join(root, "capsule.json"), receipt.CapsuleSHA256)
	if err != nil || c.Format != 2 || receipt.Format != 1 || receipt.DeploymentID != id || receipt.Host != c.Host || receipt.AuthoritySHA256 != merchantStartupAuthoritySHA(c.Baseline) || receipt.ProviderSHA256 != c.Candidate.PayloadSHA256 || receipt.PID <= 1 || !existingSchemaInvocationPattern.MatchString(receipt.InvocationID) {
		return empty, "", errors.New("predecessor is not an actually confirmed local startup baseline")
	}
	return c, receipt.CapsuleSHA256, nil
}

func (runtime *productionRuntime) closeMerchantStartupAdmission(ctx context.Context, id, repo, predecessor string) (string, error) {
	root, err := runtime.startupBaselineRoot(id)
	if err != nil {
		return "", err
	}
	if err := runtime.merchantStorePrivateDirectory(filepath.Join(root, "state"), true); err != nil {
		return "", err
	}
	host, err := runtime.hostname()
	if err != nil {
		return "", err
	}
	registered := false
	for _, origin := range merchantStartupOrigins {
		registered = registered || host == origin.Host
	}
	if !registered {
		return "", errors.New("startup close host is not a registered origin")
	}
	p, err := runtime.startupBaselineProvider(ctx, root, repo, "candidate")
	if err != nil {
		return "", err
	}
	if !validMerchantStoreCapability(p.MerchantStoreWriterCapability) {
		return "", errors.New("startup provider has no supported writer gate")
	}
	loaded, err := runtime.loadedExistingSchemaUnit(ctx)
	if err != nil {
		return "", err
	}
	state, err := runtime.billingUnitState(ctx, runtime.paths.Service)
	pid, parseErr := strconv.Atoi(state["MainPID"])
	if err != nil || parseErr != nil || pid <= 1 || state["ActiveState"] != "active" || state["SubState"] != "running" || state["MainPID"] != loaded["MainPID"] || state["InvocationID"] != loaded["InvocationID"] || !existingSchemaInvocationPattern.MatchString(state["InvocationID"]) {
		return "", errors.New("startup close legacy running generation unavailable")
	}
	var legacy productionReleasePackagePlan
	var values map[string]string
	var startup, gate string
	if predecessor == "" {
		legacy, err = runtime.startupBaselineProvider(ctx, root, repo, "preactivation")
		if err != nil {
			return "", err
		}
		values, startup, err = runtime.startupBaselineLegacyValues(ctx, loaded, pid)
		if err != nil {
			return "", err
		}
		unit, err := runtime.runner.Run(ctx, productionCommand{Name: commandBsdtar, Args: []string{"-xOf", filepath.Join(root, legacy.PackagePath), "usr/lib/systemd/system/lmm-api.service"}, OutputLimit: 1 << 20})
		if err != nil {
			return "", errors.New("legacy signed unit unavailable")
		}
		actual, err := runtime.readExistingSchemaSealedFile(loaded["FragmentPath"], false)
		if err != nil || !bytes.Equal(actual, unit) {
			return "", errors.New("legacy loaded fragment differs from exact official preactivation package")
		}
		gate = "MISSING_PRE_VARIANT"
	} else {
		previous, digest, err := runtime.startupBaselineConfirmed(predecessor)
		if err != nil {
			return "", err
		}
		if previous.Candidate != p {
			return "", errors.New("successor startup baseline must retain the same exact official provider")
		}
		if err := runtime.verifyPortableRunningWriter(ctx, previous, digest, "", false); err != nil {
			return "", err
		}
		legacy = previous.Candidate
		values, err = runtime.merchantStoreCapsuleStartup(ctx, previous, digest, loaded)
		if err != nil {
			return "", err
		}
		startup = previous.Writer.StartupSHA256
		gate = "CONFIRMED_BASELINE:" + merchantStartupAuthoritySHA(previous.Baseline)
	}
	if runtime.verifyMerchantStorePortableInstalled(productionMerchantStoreCapsule{Binary: runtime.paths.InstalledBinary}, legacy.PayloadSHA256) != nil || sha256MustEqual(filepath.Join("/proc", strconv.Itoa(pid), "exe"), legacy.PayloadSHA256) != nil {
		return "", errors.New("startup close installed/running legacy provider differs from official evidence")
	}
	db, err := captureMerchantStartupDatabase(ctx, values)
	if err != nil {
		return "", err
	}
	if db.ReservedOwners {
		return "", errors.New("startup close found a live/unknown durable deployment owner")
	}
	if predecessor == "" && (len(db.FloorValues) != 0 || !db.PreVariant) {
		return "", errors.New("first conversion requires actual missing gate and pre-variant schema")
	}
	path := filepath.Join(runtime.paths.NginxRoot, "lmm-api-locations.conf")
	original, err := runtime.readExistingSchemaSealedFile(path, false)
	if err != nil {
		return "", err
	}
	if predecessor != "" && bytes.Contains(original, []byte(merchantStartupAdmissionKind)) {
		previousRoot, err := runtime.startupBaselineRoot(predecessor)
		if err != nil {
			return "", err
		}
		var priorClose productionMerchantStartupClose
		if _, err := runtime.startupBaselineRead(filepath.Join(previousRoot, "state", "baseline-close.json"), &priorClose); err != nil {
			return "", err
		}
		priorOriginal, err := runtime.readExistingSchemaSealedFile(filepath.Join(previousRoot, "state", "admission-original.conf"), true)
		if err != nil {
			return "", err
		}
		priorBarrier, err := merchantStartupAdmissionBarrier(priorOriginal, predecessor)
		if err != nil || startupContentSHA256(priorOriginal) != priorClose.OriginalSHA256 || !bytes.Equal(priorBarrier, original) {
			return "", errors.New("predecessor persistent admission bytes differ")
		}
		original = priorOriginal
	}
	barrier, err := merchantStartupAdmissionBarrier(original, id)
	if err != nil {
		return "", err
	}
	close := productionMerchantStartupClose{Format: 1, DeploymentID: id, Host: host, Provider: p, Legacy: legacy, PID: pid, InvocationID: state["InvocationID"], StartupSHA256: startup, OriginalSHA256: startupContentSHA256(original), AdmissionSHA256: startupContentSHA256(barrier), GateBefore: gate, Database: db}
	// Save exact pre-change facts first. An interrupted close cannot invent the
	// later loaded proof; baseline-capture independently reobserves it.
	if err := runtime.startupBaselineNewBytes(filepath.Join(root, "state", "admission-original.conf"), original); err != nil {
		return "", err
	}
	if err := runtime.startupBaselineNewFile(filepath.Join(root, "state", "baseline-close.json"), close); err != nil {
		return "", err
	}
	if err := runtime.installAdmissionBarrier(ctx, barrier); err != nil {
		return "", err
	}
	if err := runtime.awaitAdmissionDrain(ctx, func(ctx context.Context) bool { return runtime.probeMerchantStartupAdmission(ctx, id) == nil }); err != nil {
		return "", err
	}
	if _, _, _, err := runtime.startupBaselineAdmission(ctx, id, close.AdmissionSHA256); err != nil {
		return "", err
	}
	current, err := runtime.billingUnitState(ctx, runtime.paths.Service)
	if err != nil || current["MainPID"] != state["MainPID"] || current["InvocationID"] != state["InvocationID"] || sha256MustEqual(filepath.Join("/proc", strconv.Itoa(pid), "exe"), legacy.PayloadSHA256) != nil {
		return "", errors.New("legacy generation changed during admission close")
	}
	raw, _ := merchantStartupJSON(close)
	return startupContentSHA256(raw), nil
}

func (runtime *productionRuntime) captureMerchantStartupHost(ctx context.Context, id string) (productionMerchantStartupHostCapture, error) {
	var h productionMerchantStartupHostCapture
	root, err := runtime.startupBaselineRoot(id)
	if err != nil {
		return h, err
	}
	var close productionMerchantStartupClose
	closeRaw, err := runtime.startupBaselineRead(filepath.Join(root, "state", "baseline-close.json"), &close)
	if err != nil {
		return h, err
	}
	host, err := runtime.hostname()
	if err != nil || close.Format != 1 || close.DeploymentID != id || host != close.Host || !productionSHA256Pattern.MatchString(close.StartupSHA256) || !productionSHA256Pattern.MatchString(close.Legacy.PayloadSHA256) {
		return h, errors.New("startup capture does not match this native close owner")
	}
	state, err := runtime.billingUnitState(ctx, runtime.paths.Service)
	if err != nil || state["MainPID"] != "0" || state["ActiveState"] != "inactive" || state["SubState"] != "dead" || state["ControlGroup"] != "" {
		return h, errors.New("startup capture requires a stopped writer and empty cgroup")
	}
	if _, err := os.Stat(filepath.Join("/proc", strconv.Itoa(close.PID))); !errors.Is(err, os.ErrNotExist) {
		return h, errors.New("old writer PID still exists; no PID inference allowed")
	}
	// The service's normal stop result must belong to the captured invocation.
	if state["InvocationID"] != close.InvocationID || cleanBillingUnitExit(state, close.PID) != nil {
		return h, errors.New("old writer did not verifiably exit normally")
	}
	loaded, err := runtime.loadedExistingSchemaUnit(ctx)
	if err != nil {
		return h, err
	}
	path := filepath.Join(root, "capsule.json")
	placeholder := strings.Repeat("0", 64)
	// A literal placeholder is permitted only while stopped and before sealing.
	// It cannot load a nonexistent capsule, and fails closed across reboot.
	commands, err := runtime.merchantStorePortableStartupCommands(loaded, runtime.paths.InstalledBinary, path, placeholder)
	if err != nil {
		return h, err
	}
	values, err := parseExistingSchemaLoadedEnvironment(loaded["Environment"])
	if err != nil || verifyExistingSchemaStartupEnvironment(values, true) != nil {
		return h, errors.New("pending startup does not enforce verify-only")
	}
	values, startup, unit, err := runtime.existingSchemaSealedStartupCommands(ctx, loaded, values, commands)
	if err != nil {
		return h, err
	}
	main, err := runtime.readExistingSchemaSealedFile(filepath.Join(runtime.paths.ConfigDir, "lmm-api-go.env"), true)
	if err != nil {
		return h, err
	}
	configured, err := parseProductionEnvironment(main)
	if err != nil {
		return h, errors.New("startup canonical main environment malformed")
	}
	mainDSN, mainErr := productionDatabaseURL(configured)
	effectiveDSN, effectiveErr := productionDatabaseURL(values)
	if mainErr != nil || effectiveErr != nil || mainDSN != effectiveDSN || verifyExistingSchemaStartupEnvironment(configured, false) != nil {
		return h, errors.New("startup effective database differs from canonical main configuration")
	}
	db, err := captureMerchantStartupDatabase(ctx, values)
	if err != nil {
		return h, err
	}
	if !merchantStartupSameDatabase(db, close.Database) || db.OtherClients != 0 || db.ReservedOwners || len(db.FloorValues) != 1 {
		return h, errors.New("stopped capture found a changed physical database, remaining client, owner or ambiguous gate")
	}
	floor, err := strconv.Atoi(db.FloorValues[0])
	if err != nil || strconv.Itoa(floor) != db.FloorValues[0] || !validMerchantStoreCapability(floor) || close.GateBefore == "MISSING_PRE_VARIANT" && floor != 1 {
		return h, errors.New("post-prepare floor is not the explicit initial/successor gate")
	}
	child, err := runtime.existingSchemaMigrationValues(values, db.Schema)
	if err != nil {
		return h, err
	}
	childValues := map[string]string{}
	for _, row := range child {
		k, v, _ := strings.Cut(row, "=")
		childValues[k] = v
	}
	dsn, env, err := productionDatabaseCommand(childValues)
	if err != nil {
		return h, err
	}
	metadata, err := runtime.runner.Run(ctx, productionCommand{Name: commandPSQL, Args: []string{"-X", "-q", "-v", "ON_ERROR_STOP=1", "--no-align", "--tuples-only", "--dbname", dsn, "--command", existingSchemaMetadataQuery(db.Schema)}, Env: env, Sensitive: true, Timeout: 30 * time.Second, OutputLimit: 8 << 20})
	if err != nil {
		return h, errors.New("startup capture actual schema metadata unavailable")
	}
	schema, err := decodeExistingSchemaSnapshot(metadata)
	if err != nil {
		return h, err
	}
	schema.StartupSHA256, schema.SignedUnitSHA256 = startup, unit
	npid, ninv, ngeneration, err := runtime.startupBaselineAdmission(ctx, id, close.AdmissionSHA256)
	if err != nil {
		return h, err
	}
	// The package verifier below repeats official issuer/layout/unit/hash checks;
	// source reachability was verified by the native close owner before mutation.
	identity := &productionMerchantStoreWriterContract{Format: 1, RequiredCapability: floor, SystemIdentifier: db.SystemIdentifier, Database: db.Database, DatabaseOID: db.DatabaseOID, Schema: db.Schema, SchemaOID: db.SchemaOID, Role: db.Role, StartupSHA256: startup, SignedUnitSHA256: unit, RecoveryPolicy: "startup-only", Candidate: productionMerchantStoreWriterTarget{Capability: close.Provider.MerchantStoreWriterCapability, PackageSHA256: close.Provider.PackageSHA256, PayloadSHA256: close.Provider.PayloadSHA256, SourceRevision: close.Provider.GitRevision, ReleaseAssetSHA256: close.Provider.ReleaseAssetSHA256}}
	c := productionMerchantStoreCapsule{Format: 2, Root: root, DeploymentID: id, Host: host, Service: runtime.paths.Service, Binary: runtime.paths.InstalledBinary, ConfigDir: runtime.paths.ConfigDir, Writer: identity, Candidate: close.Provider, ExistingSchemaContract: &schema, StartupPolicy: "per-start", SchemaMode: productionSchemaModeVerifyExisting}
	provider, err := runtime.verifyMerchantStoreCapsuleArtifact(ctx, c, false)
	if err != nil {
		return h, err
	}
	if err := runtime.verifyMerchantStorePortableInstalled(c, close.Provider.PayloadSHA256); err != nil {
		return h, err
	}
	status, err := runVerifiedBinary(ctx, runtime.runner, provider, []string{"merchant-store-writer-gate", "status"}, child, filepath.Dir(provider), 35*time.Second, true)
	actual, parseErr := parseMerchantStoreWriterStatus(status)
	if err != nil || parseErr != nil || actual.RequiredCapability != floor || actual.WriterCapability != close.Provider.MerchantStoreWriterCapability || !actual.NewWritesAllowed {
		return h, errors.New("startup capture actual provider status invalid")
	}
	if err := runtime.verifyMerchantStoreWriterProvider(ctx, merchantStoreCapsuleWorkspace(c), provider, child, "candidate"); err != nil {
		return h, err
	}
	// Recheck remaining clients and unchanged startup/admission after children
	// exited. No long-lived outer lock can deadlock their own verify lock.
	afterDB, err := captureMerchantStartupDatabase(ctx, values)
	if err != nil || !merchantStartupSameDatabase(db, afterDB) || afterDB.OtherClients != 0 || afterDB.ReservedOwners || !stringsEqual(db.FloorValues, afterDB.FloorValues) {
		return h, errors.New("startup capture database changed while verifying provider")
	}
	after, err := runtime.loadedExistingSchemaUnit(ctx)
	if err != nil || after["MainPID"] != "0" || after["ActiveState"] != "inactive" || after["ExecStartPre"] != loaded["ExecStartPre"] || after["ExecStartPreEx"] != loaded["ExecStartPreEx"] || after["DropInPaths"] != loaded["DropInPaths"] || after["Environment"] != loaded["Environment"] || after["EnvironmentFiles"] != loaded["EnvironmentFiles"] {
		return h, errors.New("startup changed during stopped qualification")
	}
	finalCommands, err := runtime.merchantStorePortableStartupCommands(after, runtime.paths.InstalledBinary, path, placeholder)
	if err != nil {
		return h, err
	}
	finalValues, err := parseExistingSchemaLoadedEnvironment(after["Environment"])
	if err != nil {
		return h, err
	}
	_, finalStartup, finalUnit, err := runtime.existingSchemaSealedStartupCommands(ctx, after, finalValues, finalCommands)
	if err != nil || finalStartup != startup || finalUnit != unit {
		return h, errors.New("startup private file bytes changed during provider qualification")
	}
	finalMetadata, err := runtime.runner.Run(ctx, productionCommand{Name: commandPSQL, Args: []string{"-X", "-q", "-v", "ON_ERROR_STOP=1", "--no-align", "--tuples-only", "--dbname", dsn, "--command", existingSchemaMetadataQuery(db.Schema)}, Env: env, Sensitive: true, Timeout: 30 * time.Second, OutputLimit: 8 << 20})
	if err != nil {
		return h, errors.New("startup final schema recheck failed")
	}
	finalSchema, err := decodeExistingSchemaSnapshot(finalMetadata)
	expectedSchema := schema
	expectedSchema.StartupSHA256, expectedSchema.SignedUnitSHA256 = "", ""
	if err != nil || finalSchema != expectedSchema {
		return h, errors.New("startup schema changed during provider qualification")
	}
	finalPID, finalInvocation, finalGeneration, err := runtime.startupBaselineAdmission(ctx, id, close.AdmissionSHA256)
	if err != nil {
		return h, err
	}
	if finalPID != npid || finalInvocation != ninv || finalGeneration != ngeneration {
		return h, errors.New("startup admission loaded generation changed during provider qualification")
	}
	h = productionMerchantStartupHostCapture{Format: 1, DeploymentID: id, Host: host, ProviderSHA256: close.Provider.PayloadSHA256, AdmissionSHA256: close.AdmissionSHA256, AdmissionBodySHA256: startupContentSHA256([]byte(merchantStartupAdmissionBody(id))), NginxPID: npid, NginxInvocationID: ninv, NginxGenerationSHA256: ngeneration, StartupBarrierKind: "sealed-pending-hook", StartupBarrierSHA256: startupContentSHA256(merchantStorePortableHookBytes(runtime.paths.InstalledBinary, path, placeholder)), LegacyPID: close.PID, LegacyInvocationID: close.InvocationID, LegacyPayloadSHA256: close.Legacy.PayloadSHA256, LegacyStartupSHA256: close.StartupSHA256, CloseSHA256: startupContentSHA256(closeRaw), StatusSHA256: startupContentSHA256(status), GateBefore: close.GateBefore, Schema: schema, Role: db.Role, RequiredCapability: floor, OtherBusinessClients: 0}
	return h, validateMerchantStartupHostCapture(h, id, close.Provider.PayloadSHA256)
}

func stringsEqual(a, b []string) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}

// The same native controller transport derives BOTH live origin facts. It
// never reads a caller-selected closure file or trusts DNS to choose an origin.
func (runtime *productionRuntime) collectMerchantStartupClosure(ctx context.Context, id string, provider productionReleasePackagePlan) ([]productionMerchantStartupHostCapture, error) {
	release := productionReleaseRuntime{runner: runtime.runner, now: runtime.now}
	var hosts []productionMerchantStartupHostCapture
	for _, origin := range merchantStartupOrigins {
		if err := release.assertRemoteHost(ctx, origin.Alias, origin.Host); err != nil {
			return nil, err
		}
		out, err := release.ssh(ctx, origin.Alias, 20*time.Second, "sudo", "-n", "/usr/bin/sha256sum", runtime.paths.InstalledBinary)
		fields := strings.Fields(string(out))
		if err != nil || len(fields) != 2 || fields[0] != provider.PayloadSHA256 || fields[1] != runtime.paths.InstalledBinary {
			return nil, errors.New("remote baseline capture provider is not the exact installed official ELF")
		}
		raw, err := release.ssh(ctx, origin.Alias, 5*time.Minute, "sudo", "-n", runtime.paths.InstalledBinary, "operator", "production", "writer-capsule", "baseline-capture", "--id", id)
		if err != nil || len(raw) > 16384 || !merchantStoreUniqueJSON(raw) {
			return nil, errors.New("remote baseline actual capture failed")
		}
		var h productionMerchantStartupHostCapture
		d := json.NewDecoder(bytes.NewReader(raw))
		d.DisallowUnknownFields()
		if d.Decode(&h) != nil || d.Decode(&struct{}{}) != io.EOF {
			return nil, errors.New("remote baseline capture invalid")
		}
		canonical, _ := merchantStartupJSON(h)
		if !bytes.Equal(canonical, raw) || h.Host != origin.Host || validateMerchantStartupHostCapture(h, id, provider.PayloadSHA256) != nil {
			return nil, errors.New("remote baseline capture host/provider/closed facts differ")
		}
		hosts = append(hosts, h)
	}
	return hosts, nil
}

func (runtime *productionRuntime) sealMerchantStartupBaseline(ctx context.Context, id, repo string, successor bool) (string, error) {
	root, err := runtime.startupBaselineRoot(id)
	if err != nil {
		return "", err
	}
	p, err := runtime.startupBaselineProvider(ctx, root, repo, "candidate")
	if err != nil {
		return "", err
	}
	hosts, err := runtime.collectMerchantStartupClosure(ctx, id, p)
	if err != nil {
		return "", err
	}
	b := &productionMerchantStartupBaseline{Kind: merchantStartupBaselineKind, Provider: p, RequiredCapability: hosts[0].RequiredCapability, Role: hosts[0].Role, StatusSHA256: hosts[0].StatusSHA256, Closure: productionMerchantStartupClosure{Format: 1, DeploymentID: id, ProviderSHA256: p.PayloadSHA256, Hosts: hosts}}
	if strings.HasPrefix(hosts[0].GateBefore, "CONFIRMED_BASELINE:") {
		b.PredecessorSHA256 = strings.TrimPrefix(hosts[0].GateBefore, "CONFIRMED_BASELINE:")
	}
	if successor != (b.PredecessorSHA256 != "") {
		return "", errors.New("initial seal and explicit confirmed successor rebind are separate authorities")
	}
	if err := validateMerchantStartupBaseline(b); err != nil {
		return "", err
	}
	// Reobserve after all verifiers, before immutable output. No origin can
	// disappear or change its startup/DB/admission generation during sealing.
	again, err := runtime.collectMerchantStartupClosure(ctx, id, p)
	if err != nil {
		return "", err
	}
	a, _ := json.Marshal(hosts)
	z, _ := json.Marshal(again)
	if !bytes.Equal(a, z) {
		return "", errors.New("closed origin proof changed during baseline sealing")
	}
	if err := runtime.merchantStorePrivateDirectory(filepath.Join(root, "state"), true); err != nil {
		return "", err
	}
	for _, h := range hosts {
		schema := h.Schema
		c := productionMerchantStoreCapsule{Format: 2, DeploymentID: id, ControllerPlanSHA256: merchantStartupAuthoritySHA(b), Root: root, Host: h.Host, Service: runtime.paths.Service, Binary: runtime.paths.InstalledBinary, ConfigDir: runtime.paths.ConfigDir, SchemaMode: productionSchemaModeVerifyExisting, ExistingSchemaContract: &schema, StartupPolicy: "per-start", Baseline: b}
		if err := validateMerchantStartupBaselineCapsule(c, runtime.paths); err != nil {
			return "", err
		}
		// Controller outputs are fixed new private files. The reviewed native
		// first-conversion owner copies unchanged bytes to each capsule.json.
		if err := runtime.startupBaselineNewFile(filepath.Join(root, "state", "sealed-"+h.Host+".json"), startupBaselineWire(c)); err != nil {
			return "", err
		}
	}
	return merchantStartupAuthoritySHA(b), nil
}

// Marshal through the wire projection so neither runtime candidate nor an
// invented retained provider can be introduced by generic struct encoding.
func startupBaselineWire(c productionMerchantStoreCapsule) json.RawMessage {
	raw, _ := canonicalMerchantStartupBaselineCapsule(c)
	return bytes.TrimSpace(raw)
}

func (runtime *productionRuntime) bindMerchantStartupBaseline(ctx context.Context, id string) (string, error) {
	root, err := runtime.startupBaselineRoot(id)
	if err != nil {
		return "", err
	}
	raw, err := runtime.readExistingSchemaSealedFile(filepath.Join(root, "capsule.json"), true)
	if err != nil {
		return "", err
	}
	digest := startupContentSHA256(raw)
	c, err := runtime.loadMerchantStoreCapsule(filepath.Join(root, "capsule.json"), digest)
	if err != nil || c.Format != 2 {
		return "", errors.New("baseline bind requires the canonical single-provider capsule")
	}
	h, err := runtime.captureMerchantStartupHost(ctx, id)
	if err != nil {
		return "", err
	}
	matched := false
	for _, expected := range c.Baseline.Closure.Hosts {
		if expected.Host == c.Host {
			left, _ := json.Marshal(h)
			right, _ := json.Marshal(expected)
			matched = bytes.Equal(left, right)
		}
	}
	if !matched {
		return "", errors.New("baseline bind current closed capture differs from immutable authority")
	}
	path := filepath.Join(root, "capsule.json")
	hook := merchantStorePortableHookBytes(runtime.paths.InstalledBinary, path, digest)
	dropIn := filepath.Join(runtime.paths.DropInDir, "90-merchant-startup-baseline.conf")
	if err := writeAtomicRegularFile(dropIn, hook, 0644); err != nil {
		return "", err
	}
	if _, err := runtime.runner.Run(ctx, productionCommand{Name: commandSystemctl, Args: []string{"daemon-reload"}, Timeout: 15 * time.Second}); err != nil {
		return "", err
	}
	loaded, err := runtime.loadedExistingSchemaUnit(ctx)
	if err != nil || loaded["MainPID"] != "0" || loaded["ActiveState"] != "inactive" {
		return "", errors.New("writer changed while binding the sealed startup hook")
	}
	if _, err := runtime.merchantStoreCapsuleStartup(ctx, c, digest, loaded); err != nil {
		return "", err
	}
	return digest, nil
}

type productionMerchantStartupSucceeded struct {
	Format        int                               `json:"format"`
	CapsuleSHA256 string                            `json:"capsule_sha256"`
	Owner         productionMerchantStoreFenceOwner `json:"owner"`
	PID           int                               `json:"pid"`
	InvocationID  string                            `json:"invocation_id"`
}

// Called only after the existing holder completed its same-session exact CAS.
// It grants no deletion permission; a missing completion receipt blocks confirm.
func (runtime *productionRuntime) recordMerchantStartupSucceeded(ctx context.Context, c productionMerchantStoreCapsule, digest string, owner productionMerchantStoreFenceOwner) error {
	if c.Format != 2 {
		return nil
	}
	state, err := runtime.billingUnitState(ctx, c.Service)
	pid, parseErr := strconv.Atoi(state["MainPID"])
	if err != nil || parseErr != nil || pid <= 1 || state["ActiveState"] != "active" || state["SubState"] != "running" || state["InvocationID"] != owner.StartInvocationID || owner.Purpose != "start" {
		return errors.New("baseline completion lost actual running generation after CAS")
	}
	return runtime.startupBaselineNewFile(filepath.Join(c.Root, "state", "start-"+owner.StartInvocationID, "startup-succeeded.json"), productionMerchantStartupSucceeded{Format: 1, CapsuleSHA256: digest, Owner: owner, PID: pid, InvocationID: state["InvocationID"]})
}

func validateMerchantStartupCompletion(c productionMerchantStoreCapsule, digest string, state map[string]string, succeeded productionMerchantStartupSucceeded) error {
	o := succeeded.Owner
	w := c.Writer
	if w == nil || succeeded.Format != 1 || succeeded.CapsuleSHA256 != digest || succeeded.InvocationID != state["InvocationID"] || strconv.Itoa(succeeded.PID) != state["MainPID"] || succeeded.PID <= 1 ||
		validateMerchantStoreFenceOwner(o) != nil || o.Purpose != "start" || o.Host != c.Host || o.DeploymentID != c.DeploymentID || o.StartInvocationID != state["InvocationID"] ||
		o.PlanSHA256 != digest || o.ContractSHA256 != merchantStoreFenceContractSHA(w) || o.ProviderSHA256 != c.Candidate.PayloadSHA256 ||
		o.SystemIdentifier != w.SystemIdentifier || o.Database != w.Database || o.DatabaseOID != w.DatabaseOID || o.Schema != w.Schema || o.SchemaOID != w.SchemaOID || o.Role != w.Role {
		return errors.New("startup completion lacks this invocation's exact successful holder/CAS identity")
	}
	return nil
}

func (runtime *productionRuntime) confirmMerchantStartupBaseline(ctx context.Context, id string) (string, error) {
	root, err := runtime.startupBaselineRoot(id)
	if err != nil {
		return "", err
	}
	raw, err := runtime.readExistingSchemaSealedFile(filepath.Join(root, "capsule.json"), true)
	if err != nil {
		return "", err
	}
	digest := startupContentSHA256(raw)
	c, err := runtime.loadMerchantStoreCapsule(filepath.Join(root, "capsule.json"), digest)
	if err != nil || c.Format != 2 {
		return "", errors.New("baseline confirm requires single-provider startup authority")
	}
	if err := runtime.verifyPortableRunningWriter(ctx, c, digest, "", false); err != nil {
		return "", err
	}
	state, err := runtime.billingUnitState(ctx, c.Service)
	if err != nil {
		return "", err
	}
	var succeeded productionMerchantStartupSucceeded
	if _, err := runtime.startupBaselineRead(filepath.Join(root, "state", "start-"+state["InvocationID"], "startup-succeeded.json"), &succeeded); err != nil {
		return "", err
	}
	if err := validateMerchantStartupCompletion(c, digest, state, succeeded); err != nil {
		return "", err
	}
	loaded, err := runtime.loadedExistingSchemaUnit(ctx)
	if err != nil {
		return "", err
	}
	values, err := runtime.merchantStoreCapsuleStartup(ctx, c, digest, loaded)
	if err != nil {
		return "", err
	}
	lease, err := acquireMerchantStartupBaselineFence(ctx, values, c.Baseline, c.Host)
	if err != nil {
		return "", err
	}
	defer lease.Close()
	if err := lease.requireNoDurableOwner(ctx); err != nil {
		return "", err
	}
	admission := ""
	for _, h := range c.Baseline.Closure.Hosts {
		if h.Host == c.Host {
			admission = h.AdmissionSHA256
		}
	}
	if _, _, _, err := runtime.startupBaselineAdmission(ctx, id, admission); err != nil {
		return "", err
	}
	confirmation := productionMerchantStartupConfirmation{Format: 1, DeploymentID: id, Host: c.Host, CapsuleSHA256: digest, AuthoritySHA256: c.ControllerPlanSHA256, PID: succeeded.PID, InvocationID: succeeded.InvocationID, ProviderSHA256: c.Candidate.PayloadSHA256}
	if err := runtime.startupBaselineNewFile(filepath.Join(root, "state", "baseline-confirmed.json"), confirmation); err != nil {
		return "", err
	}
	return digest, nil
}

// Confirmation can be reobserved after an ordinary service retry. The receipt
// remains historical; the current generation must separately pass the same
// installed/running provider, exact status/schema and successful holder proof.
func (runtime *productionRuntime) captureMerchantStartupConfirmed(ctx context.Context, id string) (productionMerchantStartupConfirmation, error) {
	var result productionMerchantStartupConfirmation
	c, digest, err := runtime.startupBaselineConfirmed(id)
	if err != nil {
		return result, err
	}
	if err := runtime.verifyPortableRunningWriter(ctx, c, digest, "", false); err != nil {
		return result, err
	}
	state, err := runtime.billingUnitState(ctx, c.Service)
	if err != nil {
		return result, err
	}
	var succeeded productionMerchantStartupSucceeded
	if _, err := runtime.startupBaselineRead(filepath.Join(c.Root, "state", "start-"+state["InvocationID"], "startup-succeeded.json"), &succeeded); err != nil {
		return result, err
	}
	if err := validateMerchantStartupCompletion(c, digest, state, succeeded); err != nil {
		return result, err
	}
	loaded, err := runtime.loadedExistingSchemaUnit(ctx)
	if err != nil {
		return result, err
	}
	values, err := runtime.merchantStoreCapsuleStartup(ctx, c, digest, loaded)
	if err != nil {
		return result, err
	}
	lease, err := acquireMerchantStartupBaselineFence(ctx, values, c.Baseline, c.Host)
	if err != nil {
		return result, err
	}
	defer lease.Close()
	if err := lease.requireNoDurableOwner(ctx); err != nil {
		return result, err
	}
	pid, _ := strconv.Atoi(state["MainPID"])
	return productionMerchantStartupConfirmation{Format: 1, DeploymentID: id, Host: c.Host, CapsuleSHA256: digest, AuthoritySHA256: c.ControllerPlanSHA256, PID: pid, InvocationID: state["InvocationID"], ProviderSHA256: c.Candidate.PayloadSHA256}, nil
}

func (runtime *productionRuntime) reopenMerchantStartupAdmission(ctx context.Context, id string) (result string, returnErr error) {
	c, digest, err := runtime.startupBaselineConfirmed(id)
	if err != nil {
		return "", err
	}
	loaded, err := runtime.loadedExistingSchemaUnit(ctx)
	if err != nil {
		return "", err
	}
	values, err := runtime.merchantStoreCapsuleStartup(ctx, c, digest, loaded)
	if err != nil {
		return "", err
	}
	// Keep one actual physical shared session across ALL remote generation
	// checks and the local nginx mutation. Returning a short-lived capture
	// receipt is not authority to open after an intervening floor activation.
	lease, err := acquireMerchantStartupBaselineFence(ctx, values, c.Baseline, c.Host)
	if err != nil {
		return "", err
	}
	defer lease.Close()
	if err := lease.requireNoDurableOwner(ctx); err != nil {
		return "", err
	}
	release := productionReleaseRuntime{runner: runtime.runner, now: runtime.now}
	for _, origin := range merchantStartupOrigins {
		if err := release.assertRemoteHost(ctx, origin.Alias, origin.Host); err != nil {
			return "", err
		}
		out, err := release.ssh(ctx, origin.Alias, 20*time.Second, "sudo", "-n", "/usr/bin/sha256sum", runtime.paths.InstalledBinary)
		parts := strings.Fields(string(out))
		if err != nil || len(parts) != 2 || parts[0] != c.Candidate.PayloadSHA256 || parts[1] != runtime.paths.InstalledBinary {
			return "", errors.New("reopen origin provider differs")
		}
		raw, err := release.ssh(ctx, origin.Alias, 3*time.Minute, "sudo", "-n", runtime.paths.InstalledBinary, "operator", "production", "writer-capsule", "baseline-confirmed-capture", "--id", id)
		var receipt productionMerchantStartupConfirmation
		if err != nil || !merchantStoreUniqueJSON(raw) {
			return "", errors.New("reopen requires both actual confirmed origins")
		}
		d := json.NewDecoder(bytes.NewReader(raw))
		d.DisallowUnknownFields()
		if d.Decode(&receipt) != nil || d.Decode(&struct{}{}) != io.EOF {
			return "", errors.New("confirmed origin receipt invalid")
		}
		canonical, _ := merchantStartupJSON(receipt)
		if !bytes.Equal(canonical, raw) || receipt.Format != 1 || receipt.Host != origin.Host || receipt.DeploymentID != id || receipt.AuthoritySHA256 != c.ControllerPlanSHA256 || receipt.ProviderSHA256 != c.Candidate.PayloadSHA256 || receipt.PID <= 1 || !existingSchemaInvocationPattern.MatchString(receipt.InvocationID) {
			return "", errors.New("confirmed origin current authority differs")
		}
	}
	var close productionMerchantStartupClose
	if _, err := runtime.startupBaselineRead(filepath.Join(c.Root, "state", "baseline-close.json"), &close); err != nil {
		return "", err
	}
	original, err := runtime.readExistingSchemaSealedFile(filepath.Join(c.Root, "state", "admission-original.conf"), true)
	if err != nil || startupContentSHA256(original) != close.OriginalSHA256 {
		return "", errors.New("native original admission backup differs")
	}
	if _, _, _, err := runtime.startupBaselineAdmission(ctx, id, close.AdmissionSHA256); err != nil {
		return "", err
	}
	barrier, err := runtime.readExistingSchemaSealedFile(filepath.Join(runtime.paths.NginxRoot, "lmm-api-locations.conf"), false)
	if err != nil || startupContentSHA256(barrier) != close.AdmissionSHA256 {
		return "", errors.New("native closed admission changed before reopen")
	}
	if err := lease.requireNoDurableOwner(ctx); err != nil {
		return "", err
	}
	writeStarted := false
	defer func() {
		if returnErr == nil || !writeStarted {
			return
		}
		// Closing admission is safe even after a physical session fails. Never
		// leave a partially reopened origin on a failed readiness/floor check.
		restoreCtx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
		defer cancel()
		restoreErr := runtime.installAdmissionBarrier(restoreCtx, barrier)
		if restoreErr == nil {
			restoreErr = runtime.awaitAdmissionDrain(restoreCtx, func(ctx context.Context) bool { return runtime.probeMerchantStartupAdmission(ctx, id) == nil })
		}
		if restoreErr == nil {
			_, _, _, restoreErr = runtime.startupBaselineAdmission(restoreCtx, id, close.AdmissionSHA256)
		}
		if restoreErr != nil {
			returnErr = errors.New("baseline reopen failed and canonical closed admission restoration was not proved")
		} else {
			returnErr = errors.New("baseline reopen failed; canonical admission was restored closed")
		}
	}()
	// The only reopened bytes are this owner's exact protected original. No
	// financial handoff or caller supplied nginx pathname participates.
	writeStarted = true
	if err := runtime.installAdmissionBarrier(ctx, original); err != nil {
		return "", err
	}
	if err := runtime.verifyPortableRunningWriter(ctx, c, digest, "", false); err != nil {
		return "", err
	}
	if err := lease.requireNoDurableOwner(ctx); err != nil {
		return "", err
	}
	return digest, nil
}

func (runtime *productionRuntime) runMerchantStartupBaseline(ctx context.Context, action, id, repo, predecessor string, stdout io.Writer) error {
	if action != "baseline-close" && predecessor != "" {
		return errors.New("predecessor applies only to an actual native close")
	}
	if action != "baseline-close" && action != "baseline-seal" && action != "baseline-rebind" && repo != "" {
		return errors.New("source checkout applies only to official close/seal verification")
	}
	var digest string
	var err error
	switch action {
	case "baseline-close":
		digest, err = runtime.closeMerchantStartupAdmission(ctx, id, repo, predecessor)
	case "baseline-capture":
		var capture productionMerchantStartupHostCapture
		capture, err = runtime.captureMerchantStartupHost(ctx, id)
		if err == nil {
			raw, _ := merchantStartupJSON(capture)
			_, err = stdout.Write(raw)
		}
		return err
	case "baseline-seal":
		digest, err = runtime.sealMerchantStartupBaseline(ctx, id, repo, false)
	case "baseline-rebind":
		digest, err = runtime.sealMerchantStartupBaseline(ctx, id, repo, true)
	case "baseline-bind":
		digest, err = runtime.bindMerchantStartupBaseline(ctx, id)
	case "baseline-confirm":
		digest, err = runtime.confirmMerchantStartupBaseline(ctx, id)
	case "baseline-confirmed-capture":
		var receipt productionMerchantStartupConfirmation
		receipt, err = runtime.captureMerchantStartupConfirmed(ctx, id)
		if err == nil {
			raw, _ := merchantStartupJSON(receipt)
			_, err = stdout.Write(raw)
		}
		return err
	case "baseline-reopen":
		digest, err = runtime.reopenMerchantStartupAdmission(ctx, id)
	default:
		return errors.New("unknown startup baseline action")
	}
	if err == nil {
		_, err = fmt.Fprintf(stdout, "startup_baseline_sha256=%s\n", digest)
	}
	return err
}
