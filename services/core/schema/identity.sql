CREATE FUNCTION core_identity.check_session_authentication() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path=pg_catalog AS $$
BEGIN
 IF TG_OP<>'INSERT' THEN
  RAISE EXCEPTION 'session authentication is append-only' USING ERRCODE='23514';
 END IF;
 IF NOT EXISTS(SELECT 1 FROM core_identity.credentials c WHERE c.id=NEW.credential_id
   AND c.kind='session' AND c.user_id=NEW.user_id AND c.user_version=NEW.user_version) THEN
  RAISE EXCEPTION 'invalid session authentication binding' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
